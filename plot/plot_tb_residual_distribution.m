function [summary, bins] = plot_tb_residual_distribution( ...
        results, pngPath, contextLabel, binWidthK)
%PLOT_TB_RESIDUAL_DISTRIBUTION 绘制模拟亮温减观测亮温的频率分布。
%   差值定义为 TBMODEL - TBSMOS；正值表示模型模拟亮温偏高。
%   纵轴为各区间样本数占全部有效样本数的百分比，不是概率密度。

    arguments
        results table
        pngPath {mustBeTextScalar}
        contextLabel {mustBeTextScalar} = ""
        binWidthK (1,1) double = NaN
    end
    required = {'TB','tbFromOIB'};
    if ~(isnan(binWidthK) || (isfinite(binWidthK) && binWidthK > 0))
        error('plot_tb_residual_distribution:BinWidth', ...
            'binWidthK 必须为正数或 NaN（自动使用 Freedman-Diaconis 分箱）。');
    end
    if ~all(ismember(required, results.Properties.VariableNames))
        error('plot_tb_residual_distribution:MissingVariable', ...
            '结果表必须包含 TB 和 tbFromOIB。');
    end

    differenceK = double(results.tbFromOIB) - double(results.TB);
    differenceK = differenceK(isfinite(differenceK));
    if isempty(differenceK)
        error('plot_tb_residual_distribution:NoData', ...
            '没有有限的亮温差值可供绘图。');
    end

    if isfinite(binWidthK)
        [counts, edges] = histcounts(differenceK, ...
            'BinWidth', binWidthK, 'Normalization', 'probability');
    else
        [counts, edges] = histcounts(differenceK, ...
            'BinMethod', 'fd', 'Normalization', 'probability');
    end
    centers = edges(1:end-1) + diff(edges) ./ 2;
    binWidth = median(diff(edges));
    bins = table(edges(1:end-1).', edges(2:end).', centers.', ...
        round(counts(:) .* numel(differenceK)), counts(:), ...
        100 .* counts(:), 'VariableNames', {'leftEdgeK','rightEdgeK', ...
        'centerK','count','frequency','frequencyPercent'});

    n = numel(differenceK);
    meanDifferenceK = mean(differenceK);
    medianDifferenceK = median(differenceK);
    standardDeviationK = std(differenceK);
    rmseK = sqrt(mean(differenceK .^ 2));
    q01K = prctile(differenceK, 1);
    q99K = prctile(differenceK, 99);
    within1p5KPercent = 100 * mean(abs(differenceK) <= 1.5);
    summary = table(n, meanDifferenceK, medianDifferenceK, ...
        standardDeviationK, rmseK, min(differenceK), q01K, q99K, ...
        max(differenceK), within1p5KPercent, binWidth, ...
        'VariableNames', {'n','meanDifferenceK','medianDifferenceK', ...
        'standardDeviationK','rmseK','minimumK','percentile1K', ...
        'percentile99K','maximumK','within1p5KPercent','binWidthK'});

    figureHandle = figure('Visible', 'off', 'Color', 'w', ...
        'Position', [80 80 980 600]);
    ax = axes(figureHandle);
    hold(ax, 'on');
    bar(ax, centers, 100 .* counts, 1.0, ...
        'FaceColor', [0.00 0.45 0.70], 'FaceAlpha', 0.82, ...
        'EdgeColor', 'w', 'LineWidth', 0.7, ...
        'DisplayName', sprintf('样本频率（n=%d）', n));
    xline(ax, 0, '-', 'Color', [0.80 0.20 0.15], 'LineWidth', 1.8, ...
        'DisplayName', '零差值');
    xline(ax, meanDifferenceK, '--', 'Color', [0.90 0.62 0.00], ...
        'LineWidth', 1.8, ...
        'DisplayName', sprintf('均值 %+.2f K', meanDifferenceK));
    xline(ax, medianDifferenceK, ':', 'Color', [0.00 0.62 0.45], ...
        'LineWidth', 2.0, ...
        'DisplayName', sprintf('中位数 %+.2f K', medianDifferenceK));

    grid(ax, 'on');
    box(ax, 'on');
    ax.GridAlpha = 0.18;
    ax.FontName = 'Microsoft YaHei';
    ax.FontSize = 11;
    xlim(ax, [edges(1), edges(end)]);
    ylim(ax, [0, 100 .* max(counts) * 1.18]);
    xlabel(ax, '\DeltaT_B = T_{B,sim} - T_{B,SMOS}（K）', ...
        'FontName', 'Microsoft YaHei', 'FontSize', 12);
    ylabel(ax, '分布频率（%）', ...
        'FontName', 'Microsoft YaHei', 'FontSize', 12);
    titleText = "模拟亮温与 SMOS 观测亮温的差值分布";
    if strlength(string(contextLabel)) > 0
        titleText = titleText + newline + string(contextLabel);
    end
    title(ax, titleText, 'FontName', 'Microsoft YaHei', ...
        'FontWeight', 'bold', 'FontSize', 13);
    legend(ax, 'Location', 'northwest', 'FontName', 'Microsoft YaHei');
    text(ax, 0.985, 0.73, sprintf([ ...
        'RMSE = %.2f K\n标准差 = %.2f K\n' ...
        '|ΔTB| ≤ 1.5 K：%.1f%%\n1%%–99%%：%.2f 至 %.2f K'], ...
        rmseK, standardDeviationK, within1p5KPercent, q01K, q99K), ...
        'Units', 'normalized', 'HorizontalAlignment', 'right', ...
        'VerticalAlignment', 'top', 'FontName', 'Microsoft YaHei', ...
        'FontSize', 10, 'BackgroundColor', 'w', ...
        'EdgeColor', [0.00 0.45 0.70], 'Margin', 5, ...
        'Interpreter', 'none');

    pngPath = char(string(pngPath));
    outputDirectory = fileparts(pngPath);
    if ~isempty(outputDirectory) && ~isfolder(outputDirectory)
        mkdir(outputDirectory);
    end
    exportgraphics(figureHandle, pngPath, 'Resolution', 300);
    close(figureHandle);
end
