% 多源联合反演入口。先运行 main 完成同日 OIB--亮温配准。
% 默认逐条运行两条求解路线

matlabRoot = fileparts(mfilename('fullpath'));
addpath(matlabRoot);
if ~exist('retrievalConfig', 'var') || isempty(retrievalConfig)
    retrievalConfig = retrieval_config();
end
addpath(retrievalConfig.paths.plotRoot);
targetYears = retrievalConfig.data.years;
outputStem = retrievalConfig.output.inversionStem;
processedRoot = retrievalConfig.paths.processedRoot;
cacheFile = fullfile(processedRoot, ...
    retrievalConfig.output.pairsStem + ".mat");
if ~isfile(cacheFile)
    error('main_inversion:MissingPairs', ...
        '缺少 %s 年配准缓存；请先运行 main。', ...
        strjoin(string(targetYears), ','));
end
load(cacheFile, 'pairs', 'summary');
if ~isequal(unique(year(summary.day)).', targetYears)
    error('main_inversion:WrongCacheYears', ...
        '反演缓存年份与 %s 不符：%s', ...
        strjoin(string(targetYears), ','), ...
        cacheFile);
end

% 每条同日配对独立反演
inputNames = {'day','flight','row','col','TB','FBice','FBsnow', ...
    'isMYI','hi','hs','nOIB'};
if retrievalConfig.temperature.source == "oib_kt19"
    if ~ismember('surfaceTempC', pairs.Properties.VariableNames)
        error('main_inversion:MissingSurfaceTemperature', ...
            'OIB 表温模式的配对缓存缺少 surfaceTempC；请先重新运行 main。');
    end
    inputNames{end + 1} = 'surfaceTempC';
end
inputs = pairs(ismember(year(pairs.day), targetYears), inputNames);
if isempty(inputs), error('main_inversion:NoPairs', '所选年份没有配对。'); end

% 所有物理口径和工作流参数集中在统一配置中。
model = retrievalConfig.model;
validationOptions = retrievalConfig.validation;
fprintf('%s：%d 个有效飞行日、%d 条同日配对。\n', ...
    strjoin(string(targetYears), ','), numel(unique(inputs.day)), height(inputs));
fprintf('每条配对分别使用 TB+FBice 或 TB+FBsnow；OIB hi、hs 留作验证。\n');

fprintf(['本次直接使用当前固定的 %d 层前向模型；' ...
    '不在反演前重复运行层数或参数敏感性分析。\n'], ...
    model.nIceLayers);

if ~exist('runSolver', 'var')
    runSolver = retrievalConfig.runtime.runSolver;
end
if runSolver
    % 先检查前向模型的标量调用。
    tb_forward(1, 0.1, false, model);
    n = height(inputs);
    hiRadar = nan(n, 1); hsRadar = nan(n, 1);
    hiLaser = nan(n, 1); hsLaser = nan(n, 1);
    hiLaserAlt = nan(n, 1); hsLaserAlt = nan(n, 1);
    nRadarRoots = zeros(n, 1); nLaserRoots = zeros(n, 1);
    tbFromOIB = nan(n, 1);
    solverTimer = tic;
    progressEvery = max(retrievalConfig.runtime.minimumProgressInterval, ...
        ceil(n / retrievalConfig.runtime.progressUpdateCount));
    fprintf('开始逐条反演：共 %d 条；约每 %d 条输出一次进度。\n', ...
        n, progressEvery);
    for k = 1:n
        pairConfig = retrievalConfig;
        pairModel = model;
        if retrievalConfig.temperature.source == "oib_kt19"
            pairModel.surfaceTempC = inputs.surfaceTempC(k);
            pairConfig.model = pairModel;
        end
        [radar, ~] = invert_pair( ...
            inputs.TB(k), inputs.FBice(k), "ice", inputs.isMYI(k), ...
            pairConfig);
        [laser, ~] = invert_pair( ...
            inputs.TB(k), inputs.FBsnow(k), "snow", inputs.isMYI(k), ...
            pairConfig);
        nRadarRoots(k) = numel(radar);
        nLaserRoots(k) = numel(laser);
        if ~isempty(radar)
            hiRadar(k) = radar(1).hi; hsRadar(k) = radar(1).hs;
        end
        if ~isempty(laser)
            % 论文第 5.2 节：双解时默认选雪深较小的一支作验证。
            hiLaser(k) = laser(1).hi; hsLaser(k) = laser(1).hs;
        end
        if numel(laser) > 1
            hiLaserAlt(k) = laser(2).hi; hsLaserAlt(k) = laser(2).hs;
        end
        tbFromOIB(k) = tb_forward( ...
            inputs.hi(k), inputs.hs(k), inputs.isMYI(k), pairModel);
        if k == 1 || mod(k, progressEvery) == 0 || k == n
            elapsedSeconds = toc(solverTimer);
            etaSeconds = elapsedSeconds / k * (n - k);
            fprintf(['[%d/%d, %5.1f%%] %s；已用 %.1f min，预计剩余 %.1f min；' ...
                '雷达路线有解 %d，激光路线有解 %d，激光双解 %d。\n'], ...
                k, n, 100 * k / n, ...
                char(string(inputs.day(k), 'yyyy-MM-dd')), ...
                elapsedSeconds / 60, etaSeconds / 60, ...
                nnz(nRadarRoots(1:k) > 0), nnz(nLaserRoots(1:k) > 0), ...
                nnz(nLaserRoots(1:k) > 1));
        end
    end
    results = addvars(inputs, hiRadar, hsRadar, hiLaser, hsLaser, ...
        hiLaserAlt, hsLaserAlt, nRadarRoots, nLaserRoots, tbFromOIB);
    fitAll = struct('tb', fit_retrieval(results.TB, tbFromOIB), ...
        'radarHi', fit_retrieval(results.hi, hiRadar), ...
        'radarHs', fit_retrieval(results.hs, hsRadar), ...
        'laserHi', fit_retrieval(results.hi, hiLaser), ...
        'laserHs', fit_retrieval(results.hs, hsLaser));
    nearTbThresholdK = validationOptions.nearTbThresholdK;
    nearTB = abs(tbFromOIB - inputs.TB) <= nearTbThresholdK;
    fitNear = struct('tb', fit_retrieval(results.TB(nearTB), tbFromOIB(nearTB)), ...
        'radarHi', fit_retrieval(results.hi(nearTB), hiRadar(nearTB)), ...
        'radarHs', fit_retrieval(results.hs(nearTB), hsRadar(nearTB)), ...
        'laserHi', fit_retrieval(results.hi(nearTB), hiLaser(nearTB)), ...
        'laserHs', fit_retrieval(results.hs(nearTB), hsLaser(nearTB)));
    sortedCounts = sort(results.nOIB(isfinite(results.nOIB)));
    coverageQuantile = validationOptions.highCoverageQuantile;
    coverageThreshold = sortedCounts(max(1, ...
        ceil(coverageQuantile * numel(sortedCounts))));
    highCoverage = results.nOIB >= coverageThreshold;
    fitHighCoverageTB = fit_retrieval( ...
        results.TB(highCoverage), tbFromOIB(highCoverage));
    highCoveragePercent = 100 * (1 - coverageQuantile);
    nearPrefix = "|TB误差|<=" + string(nearTbThresholdK) + " K：";
    metricNames = ["TB：全部配对"; ...
        "TB：OIB 样本数前 " + string(highCoveragePercent) + "%"; ...
        "TB+FBice：冰厚"; "TB+FBice：雪深"; ...
        "TB+FBsnow：冰厚"; "TB+FBsnow：雪深"; ...
        nearPrefix + "TB+FBice 冰厚"; ...
        nearPrefix + "TB+FBice 雪深"; ...
        nearPrefix + "TB+FBsnow 冰厚"; ...
        nearPrefix + "TB+FBsnow 雪深"];
    metricFits = {fitAll.tb; fitHighCoverageTB; fitAll.radarHi; ...
        fitAll.radarHs; fitAll.laserHi; fitAll.laserHs; ...
        fitNear.radarHi; fitNear.radarHs; fitNear.laserHi; fitNear.laserHs};
    metricSummary = table(metricNames, zeros(numel(metricNames),1), ...
        nan(numel(metricNames),1), nan(numel(metricNames),1), ...
        nan(numel(metricNames),1), nan(numel(metricNames),1), ...
        nan(numel(metricNames),1), nan(numel(metricNames),1), ...
        'VariableNames', {'metric','n','correlation','rSquared','bias', ...
        'rmse','slope','intercept'});
    for metricIndex = 1:numel(metricFits)
        currentFit = metricFits{metricIndex};
        metricSummary.n(metricIndex) = currentFit.n;
        metricSummary.correlation(metricIndex) = currentFit.correlation;
        metricSummary.rSquared(metricIndex) = currentFit.rSquared;
        metricSummary.bias(metricIndex) = currentFit.bias;
        metricSummary.rmse(metricIndex) = currentFit.rmse;
        metricSummary.slope(metricIndex) = currentFit.slope;
        metricSummary.intercept(metricIndex) = currentFit.intercept;
    end
    metricByYear = summarize_retrieval_by_year(results, nearTB, ...
        fullfile(processedRoot, outputStem + "_metrics_by_year.csv"), ...
        nearTbThresholdK);
    paperYearsMask = ismember(year(results.day), targetYears);
    metricPaperYears = summarize_retrieval_subset( ...
        results, paperYearsMask, nearTB, nearTbThresholdK);
    writetable(metricPaperYears, fullfile(processedRoot, ...
        outputStem + "_subset_metrics.csv"));
    spaceFYI = build_solution_space(false, retrievalConfig);
    spaceMYI = build_solution_space(true, retrievalConfig);
    outputFile = fullfile(processedRoot, outputStem + ".mat");
    save(outputFile, 'results', 'fitAll', 'fitNear', 'fitHighCoverageTB', ...
        'metricSummary', 'coverageThreshold', 'nearTB', 'highCoverage', ...
        'metricByYear', 'metricPaperYears', 'spaceFYI', 'spaceMYI', ...
        'model', 'retrievalConfig', '-v7.3');
    writetable(results, fullfile(processedRoot, ...
        outputStem + ".csv"));
    writetable(metricSummary, fullfile(processedRoot, ...
        outputStem + "_metrics.csv"));
    figureDir = fullfile(retrievalConfig.paths.figureRoot, outputStem);
    plot_solution_space(spaceFYI, spaceMYI, figureDir);
    plot_retrieval_validation(results, nearTB, highCoverage, ...
        figureDir, "", nearTbThresholdK, coverageQuantile);
    disp(metricSummary);
    fprintf('逐条反演总用时：%.1f min。\n', toc(solverTimer) / 60);
    fprintf('已保存反演与解空间：%s\n', outputFile);
end
