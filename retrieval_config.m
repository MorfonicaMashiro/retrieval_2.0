    config.domain = struct( ...
        'minIceThicknessM', 0, ...
        'maxIceThicknessM', 10, ...
        'minSnowDepthM', 0, ...
        'maxSnowDepthM', 1, ...
        'excludeFloodedIce', true);

    %% 8. 反演扫描和二分求根
    config.inversion = struct( ...
        'initialStepM', 0.04, ...       % TB+FBice 初始雪深步长
        'scanStepM', 0.01, ...          % TB+FBsnow 全范围扫描步长
        'tbToleranceK', 0.01, ...
        'snowToleranceM', 1e-5, ...
        'maxIterations', 60);

    %% 9. 验证、筛选和八场景验证与检查层数敏感性
    config.validation = struct();
    config.validation.nearTbThresholdK = 1.5;
    config.validation.highCoverageQuantile = 0.95;
    config.validation.closureHiToleranceM = 1e-3;
    config.validation.closureHsToleranceM = 1e-4;
    config.validation.closureTbToleranceK = 0.01;
    config.validation.layerSensitivity = struct( ...
        'iceLayerCounts', [1, 20, 100], ...
        'hiM', [0.5; 1.0; 2.5; 5.0; 0.5; 1.5; 3.0; 5.0], ...
        'hsM', [0.05; 0.10; 0.25; 0.40; 0.05; 0.15; 0.35; 0.40], ...
        'isMYI', logical([0; 0; 0; 0; 1; 1; 1; 1]));

    %% 10. 理论解空间（论文给范围，步长为本实现的数值设置）
    config.solutionSpace = struct( ...
        'iceStepM', 0.05, ...
        'snowStepM', 0.01);

    %% 11. 论文表 1/表 2 固定参考数据（不是可调物理参数）
    scenario = ["I"; "II"; "III"; "IV"; "V"; "VI"; "VII"; "VIII"];
    config.reference.table1 = struct( ...
        'scenario', scenario, ...
        'isMYI', logical([0; 0; 0; 0; 1; 1; 1; 1]), ...
        'hiM', [0.5; 1; 1.5; 2.5; 1.5; 2.5; 3; 5], ...
        'hsM', [0.05; 0.03; 0.10; 0.25; 0.15; 0.15; 0.35; 0.40], ...
        'fbIceM', [0.0376; 0.0971; 0.1284; 0.1880; ...
            0.1127; 0.2192; 0.2100; 0.4072], ...
        'fbSnowM', [0.0876; 0.1271; 0.2284; 0.4380; ...
            0.2627; 0.3692; 0.5600; 0.8072], ...
        'tbK', [231.5; 238.2; 243.7; 246.5; 243.8; 248.9; 252.0; 250.4]);
    alternateHiM = nan(8, 1); alternateHsM = nan(8, 1);
    alternateHiM([2 6]) = [0.5552; 1.5499];
    alternateHsM([2 6]) = [0.0989; 0.2971];
    config.reference.table2 = struct( ...
        'alternateHiM', alternateHiM, ...
        'alternateHsM', alternateHsM, ...
        'doubleSolutionScenarios', ["II"; "VI"]);

    %% 12. 运行开关和输出命名
    config.runtime = struct( ...
        'useCache', true, ...
        'runSolver', true, ...                  %是否全量反演
        'progressUpdateCount', 100, ...         %查找最多次数
        'minimumProgressInterval', 10);
    config.output = struct( ...
        'variantTag', "auto", ...
        'yearTag', "", ...
        'pairsStem', "", ...
        'inversionStem', "", ...
        'forwardValidationStem', "", ...
        'closureStem', "inversion_ideal_closure", ...
        'coverageFigureStem', "");

    config = merge_known_fields(config, overrides, "config");
    config = finalize_derived_fields(config);
    validate_config(config);

end

function base = merge_known_fields(base, overrides, path)
    if ~isstruct(overrides) || ~isscalar(overrides)
        error('retrieval_config:Overrides', '%s 覆盖项必须是标量结构体。', path);
    end
    names = fieldnames(overrides);
    for index = 1:numel(names)
        name = names{index};
        childPath = path + "." + string(name);
        if ~isfield(base, name)
            error('retrieval_config:UnknownField', ...
                '未知配置字段：%s。', childPath);
        end
        if isstruct(base.(name)) && isstruct(overrides.(name))
            base.(name) = merge_known_fields( ...
                base.(name), overrides.(name), childPath);
        else
            base.(name) = overrides.(name);
        end
    end
end

function config = finalize_derived_fields(config)
    % 共享解域只定义一次，再派生给需要完整 options 结构的接口。
    config.temperature.source = string(config.temperature.source);
    config.temperature.oibField = string(config.temperature.oibField);
    if config.temperature.source == "fixed"
        config.model.surfaceTempC = config.temperature.fixedC;
        config.model.brineTemperatureFloorC = NaN;
    else
        % 逐点 OIB 表温由 collocate_day 注入 model.surfaceTempC。
        config.model.brineTemperatureFloorC = ...
            config.temperature.oibBrineFloorC;
    end
    config.inversion.maxSnowDepthM = config.domain.maxSnowDepthM;
    config.inversion.maxIceThicknessM = config.domain.maxIceThicknessM;
    config.solutionSpace.minIceThicknessM = config.domain.minIceThicknessM;
    config.solutionSpace.maxIceThicknessM = config.domain.maxIceThicknessM;
    config.solutionSpace.minSnowDepthM = config.domain.minSnowDepthM;
    config.solutionSpace.maxSnowDepthM = config.domain.maxSnowDepthM;
    config.solutionSpace.excludeFloodedIce = config.domain.excludeFloodedIce;
    if config.model.limitBrinePermittivity
        brineTag = "vb70_cap";
        config.meta.brinePolicy = "cap_dielectric_input_at_70_permille";
    else
        brineTag = "vb_uncapped";
        config.meta.brinePolicy = "extrapolate_and_flag_above_70_permille";
    end
    gridVersion = string(config.data.gridVersion);
    if gridVersion == "EASE2"
        gridTag = "ease2";
    else
        gridTag = "legacy_ease";
    end
    config.meta.id = "multisensor-retrieval-v4-" + gridTag + "-" + ...
        brineTag;
    if config.temperature.source == "fixed"
        temperatureTag = "fixed_temp";
    else
        temperatureTag = "oib_kt19";
    end
    tbSource = string(config.data.brightnessTemperatureSource);
    if tbSource == "smap"
        sensorTag = "_smap" + string(config.data.smap.activeProduct);
    else
        sensorTag = "";
    end
    if string(config.output.variantTag) == "auto"
        coldTag = "";
        if string(config.model.brineColdExtrapolationMode) == ...
                "linear_below_minus30"
            coldTag = "_cold_linear";
        end
        config.output.variantTag = gridTag + "_" + brineTag + "_" + ...
            temperatureTag + ...
            coldTag + sensorTag + "_stride" + ...
            string(config.collocation.centerStride);
    end
    config.output.yearTag = strjoin(string(config.data.years), '_');
    config.output.pairsStem = ...
        "pairs_" + config.output.yearTag + "_" + ...
        string(config.output.variantTag) + "_same_day";
    config.output.inversionStem = ...
        "inversion_" + config.output.yearTag + "_" + ...
        string(config.output.variantTag);
    config.output.forwardValidationStem = ...
        "tb_forward_" + string(config.output.variantTag);
    config.output.coverageFigureStem = ...
        config.output.pairsStem + "_coverage";
end

function validate_config(config)
    years = config.data.years;
    if ~isnumeric(years) || isempty(years) || any(~isfinite(years)) || ...
            any(years ~= fix(years)) || numel(unique(years)) ~= numel(years)
        error('retrieval_config:Years', 'data.years 必须是不重复的整数年份。');
    end
    gridVersion = string(config.data.gridVersion);
    if ~isscalar(gridVersion) || ~ismember(gridVersion, ["EASE", "EASE2"])
        error('retrieval_config:GridVersion', ...
            'data.gridVersion 只能为 EASE 或 EASE2。');
    end
    windowSize = config.collocation.windowSize;
    if ~isscalar(windowSize) || windowSize < 1 || ...
            windowSize ~= fix(windowSize) || mod(windowSize, 2) ~= 1
        error('retrieval_config:Window', ...
            'collocation.windowSize 必须是正奇数。');
    end
    stride = config.collocation.centerStride;
    phase = config.collocation.centerPhase;
    if ~isscalar(stride) || ~isfinite(stride) || stride < 1 || ...
            stride ~= fix(stride) || ~isnumeric(phase) || ...
            ~isequal(size(phase), [1 2]) || any(~isfinite(phase)) || ...
            any(phase ~= fix(phase)) || any(phase < 1) || ...
            any(phase > stride)
        error('retrieval_config:Stride', ...
            'centerStride 必须为正整数，centerPhase 必须位于该步长内。');
    end
    source = string(config.temperature.source);
    if ~isscalar(source) || ~ismember(source, ["fixed", "oib_kt19"])
        error('retrieval_config:TemperatureSource', ...
            'temperature.source 只能为 fixed 或 oib_kt19。');
    end
    coldMode = string(config.model.brineColdExtrapolationMode);
    if ~isscalar(coldMode) || ...
            ~ismember(coldMode, ["none", "linear_below_minus30"])
        error('retrieval_config:ColdBrineExtrapolation', ...
            ['model.brineColdExtrapolationMode 只能为 none 或 ' ...
            'linear_below_minus30。']);
    end
    tbSource = string(config.data.brightnessTemperatureSource);
    if ~isscalar(tbSource) || ~ismember(tbSource, ["smos", "smap"])
        error('retrieval_config:TBSource', ...
            'data.brightnessTemperatureSource 只能为 smos 或 smap。');
    end
    smap = config.data.smap;
    activeProduct = string(smap.activeProduct);
    if ~isscalar(activeProduct) || ...
            ~ismember(activeProduct, ["36km", "9km"])
        error('retrieval_config:SMAPProduct', ...
            'data.smap.activeProduct 只能为 36km 或 9km。');
    end
    if ~ismember(string(smap.tbField), ...
            ["uncorrected", "surface_corrected"])
        error('retrieval_config:SMAPTBField', ...
            'data.smap.tbField 必须为 uncorrected 或 surface_corrected。');
    end
    if ~isnumeric(smap.validTBRangeK) || ...
            ~isequal(size(smap.validTBRangeK), [1 2]) || ...
            any(~isfinite(smap.validTBRangeK)) || ...
            smap.validTBRangeK(2) <= smap.validTBRangeK(1) || ...
            smap.validTBRangeK(1) < 0 || smap.validTBRangeK(2) > 400
        error('retrieval_config:SMAPTBRange', ...
            'data.smap.validTBRangeK 必须是 0--400 K 内的递增二元向量。');
    end
    if ~isnumeric(smap.requiredClearQualityBits) || ...
            any(~isfinite(smap.requiredClearQualityBits)) || ...
            any(smap.requiredClearQualityBits < 0) || ...
            any(smap.requiredClearQualityBits > 15) || ...
            any(smap.requiredClearQualityBits ~= ...
                fix(smap.requiredClearQualityBits))
        error('retrieval_config:SMAPQualityBits', ...
            'data.smap.requiredClearQualityBits 必须为 0--15 的整数。');
    end
    if ~all(ismember(string(smap.looks), ["fore", "aft"])) || ...
            isempty(smap.looks) || numel(unique(string(smap.looks))) ~= ...
            numel(smap.looks)
        error('retrieval_config:SMAPLooks', ...
            'data.smap.looks 必须由不重复的 fore/aft 组成。');
    end
    if ~isscalar(smap.primaryTimeWindowHours) || ...
            ~isscalar(smap.sensitivityTimeWindowHours) || ...
            smap.primaryTimeWindowHours <= 0 || ...
            smap.sensitivityTimeWindowHours < smap.primaryTimeWindowHours
        error('retrieval_config:SMAPTimeWindow', ...
            'SMAP 主时间窗必须为正，敏感性时间窗不得小于主时间窗。');
    end
    if ~isscalar(config.temperature.fixedC) || ...
            ~isfinite(config.temperature.fixedC) || ...
            config.temperature.fixedC >= config.model.waterTempC || ...
            strlength(config.temperature.oibField) == 0 || ...
            ~isnumeric(config.temperature.oibBrineFloorC) || ...
            ~isscalar(config.temperature.oibBrineFloorC) || ...
            ~(isnan(config.temperature.oibBrineFloorC) || ...
            (isfinite(config.temperature.oibBrineFloorC) && ...
            config.temperature.oibBrineFloorC >= -30 && ...
            config.temperature.oibBrineFloorC < 0))
        error('retrieval_config:Temperature', '表面温度配置无效。');
    end
    if config.model.rhoWater <= config.model.rhoIce || ...
            config.model.rhoIce <= config.model.rhoSnow || ...
            config.model.rhoSnow <= 0
        error('retrieval_config:Density', ...
            '需满足 rhoWater > rhoIce > rhoSnow > 0。');
    end
    inversionValues = [config.inversion.maxSnowDepthM, ...
        config.inversion.maxIceThicknessM, config.inversion.initialStepM, ...
        config.inversion.scanStepM, config.inversion.tbToleranceK, ...
        config.inversion.snowToleranceM, config.inversion.maxIterations];
    if any(~isfinite(inversionValues)) || any(inversionValues <= 0)
        error('retrieval_config:Inversion', '反演参数必须为有限正数。');
    end
    q = config.validation.highCoverageQuantile;
    if ~isscalar(q) || ~isfinite(q) || q <= 0 || q >= 1 || ...
            config.validation.nearTbThresholdK <= 0
        error('retrieval_config:Validation', '验证阈值或覆盖分位数无效。');
    end
    space = config.solutionSpace;
    if space.minIceThicknessM < 0 || ...
            space.maxIceThicknessM <= space.minIceThicknessM || ...
            space.iceStepM <= 0 || space.minSnowDepthM < 0 || ...
            space.maxSnowDepthM <= space.minSnowDepthM || ...
            space.snowStepM <= 0
        error('retrieval_config:SolutionSpace', '解空间范围或步长无效。');
    end
    table1 = config.reference.table1;
    expected = 8;
    fields = {'scenario','isMYI','hiM','hsM','fbIceM','fbSnowM','tbK'};
    for index = 1:numel(fields)
        if numel(table1.(fields{index})) ~= expected
            error('retrieval_config:Reference', ...
                'reference.table1.%s 必须含 %d 个场景。', ...
                fields{index}, expected);
        end
    end
    if strlength(string(config.output.variantTag)) == 0
