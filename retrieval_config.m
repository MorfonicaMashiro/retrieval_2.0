function config = retrieval_config(overrides)
%RETRIEVAL_CONFIG 多源海冰参数联合反演的统一配置入口。
%   CONFIG = RETRIEVAL_CONFIG() 返回分块配置：
%     meta          版本、适用范围和卤水策略
%     paths         工程目录
%     data          年份、网格和输入产品规则
%     collocation   3x3 OIB--SMOS 配准算子
%     temperature   固定表温/OIB KT19 表温切换
%     model         L 波段前向模型
%     domain        冰厚、雪深和淹没条件的共享物理解域
%     inversion     两条反演路线的扫描和二分参数
%     validation    统计筛选、闭环容差和层数检查
%     solutionSpace 理论解空间范围与步长
%     reference     论文表 1/表 2 的固定参考数据
%     runtime       缓存、求解开关和进度输出
%     output        统一输出命名
%
%   CONFIG = RETRIEVAL_CONFIG(OVERRIDES) 对已知字段作递归覆盖，
%   未知字段会报错，避免拼写错误被静默忽略。例如：
%     overrides.temperature.source = "oib_kt19";
%     overrides.model.limitBrinePermittivity = true;
%     config = retrieval_config(overrides);
%
%   只有可配置的物理假设和工作流参数放在这里。Vant、Cox--Weeks、
%   Klein--Swift 等经验公式的发表系数仍封装在各自物理函数中，不作为
%   可随意调整的运行参数。

    if nargin < 1 || isempty(overrides), overrides = struct(); end
    matlabRoot = fileparts(mfilename('fullpath'));
    workspaceRoot = fileparts(matlabRoot);

    config = struct();

    %% 1. 元数据与当前默认口径
    config.meta = struct( ...
        'id', "multisensor-retrieval-v4-ease2-vb-uncapped", ...
        'schemaVersion', 4, ...
        'status', "frozen 2026-11-09", ...
        'frozenAt', "2026-11-09", ...
        'brinePolicy', "extrapolate_and_flag_above_70_permille");

    %% 2. 工程路径（由本文件位置推导，不依赖当前工作目录）
    config.paths = struct( ...
        'workspaceRoot', workspaceRoot, ...
        'matlabRoot', matlabRoot, ...
        'dataRoot', fullfile(workspaceRoot, 'data'), ...
        'processedRoot', fullfile(matlabRoot, 'processed'), ...
        'figureRoot', fullfile(matlabRoot, 'figures'), ...
        'plotRoot', fullfile(matlabRoot, 'plot'), ...
        'gridResamplingRoot', fullfile(matlabRoot, '+grid_resampling'), ...
        'readDataRoot', fullfile(matlabRoot, 'readdata'), ...
        'readSmapRoot', fullfile(matlabRoot, 'readdata', 'readsmap'));

    %% 3. 数据年份、网格和产品文件规则
    config.data = struct();
    config.data.years = [2012, 2015];
    config.data.gridVersion = "EASE2"; % 后续默认统一使用 EASE2-N 12.5 km
    % 历史冻结结果保留原 EASE；显式覆盖为 EASE 仅用于复算旧结果。
    config.data.analysisGrid = struct( ...
        'name', "EASE2-N12.5km", ...
        'version', "EASE2", ...
        'epsg', 6931, ...
        'spacingKm', 12.5, ...
        'nRows', 1440, ...
        'nCols', 1440, ...
        'conversionFunction', "regrid_to_ease2_12p5");
    % brightnessTemperatureSource="smos" 保持冻结基线；切换到 "smap"
    % 时由 smap.activeProduct 选择标准 36 km 或增强 9 km 产品。
    config.data.brightnessTemperatureSource = "smos";
    config.data.oib = struct( ...
        'formalLastYear', 2013, ...
        'formalRelativeDirectory', fullfile('OIB', 'IDCSI4_L4'), ...
        'formalFilePattern', 'IDCSI4_*.txt', ...
        'quickLookRelativeDirectory', fullfile('OIB', 'NSIDC-0708_QuickLook'), ...
        'quickLookYearSuffix', '_GR_NASA', ...
        'quickLookFilePattern', 'OIB_*_IDCSI2*.txt');
    config.data.smos = struct( ...
        'relativeDirectory', 'smos', ...
        'filePattern', 'SMOS_TB_north_%s.nc');
    config.data.smap = struct();
    config.data.smap.activeProduct = "36km";
    config.data.smap.years = 2016:2019;
    config.data.smap.nativeGrid = "EASE2";
    config.data.smap.northEpsg = 6931;
    config.data.smap.looks = ["fore", "aft"];
    config.data.smap.tbField = "uncorrected";
    config.data.smap.requireBothPolarizations = true;
    % SMAP 质量位采用从 0 开始的编号；bit 0 为主质量判据。
    config.data.smap.requiredClearQualityBits = 0;
    config.data.smap.validTBRangeK = [50, 310];
    config.data.smap.primaryTimeWindowHours = 3;
    config.data.smap.sensitivityTimeWindowHours = 6;
    config.data.smap.comparison = struct( ...
        'targetSupport', "native_36km_ease2_cell", ...
        'smosSourceGrid', "original_ease_12p53376km", ...
        'overlapBoundarySegments', 32, ...
        'minimumSmosAreaCoverageFraction', 0.95, ...
        'primarySmapTimeStrategy', "nearest_oib_window_median");
    config.data.smap.oibMatchedDates = [ ...
        "2016-04-19", "2016-04-20", "2016-04-21", "2016-04-29", ...
        "2016-05-03", "2016-05-04", ...
        "2017-03-09", "2017-03-10", "2017-03-11", "2017-03-12", ...
        "2017-03-14", "2017-03-20", "2017-03-23", "2017-03-24", ...
        "2017-04-03", "2017-04-05", "2017-04-06", "2017-04-07", ...
        "2017-04-11", "2017-04-19", ...
        "2018-03-22", "2018-04-03", "2018-04-04", "2018-04-06", ...
        "2018-04-07", "2018-04-08", "2018-04-14", "2018-04-16", ...
        "2019-04-06", "2019-04-08", "2019-04-12", "2019-04-19", ...
        "2019-04-20", "2019-04-22"];
    config.data.smap.standard = struct( ...
        'product', "SPL1CTB.006", ...
        'shortName', "SPL1CTB", ...
        'version', "006", ...
        'resolutionKm', 36, ...
        'grid', "EASE2", ...
        'northEpsg', 6931, ...
        'relativeDirectory', fullfile('smap', 'SPL1CTB_006'), ...
        'filePattern', 'SMAP_L1C_TB_*_%sT*_R*_*.h5', ...
        'filePrefix', "SMAP_L1C_TB", ...
        'groupCandidates', ["/North_Polar_Projection", ...
            "/EASE2_North_Polar_Projection"]);
    config.data.smap.enhanced = struct( ...
        'product', "SPL1CTB_E.004", ...
        'shortName', "SPL1CTB_E", ...
        'version', "004", ...
        'resolutionKm', 9, ...
        'grid', "EASE2", ...
        'northEpsg', 6931, ...
        'relativeDirectory', fullfile('smap', 'SPL1CTB_E_004'), ...
        'filePattern', 'SMAP_L1C_TB_E_*_%sT*_R*_*.h5', ...
        'filePrefix', "SMAP_L1C_TB_E", ...
        'groupCandidates', ["/North_Polar_Projection", ...
            "/EASE2_North_Polar_Projection"]);

    %% 4. 空间配准：当前试验统一使用互不重叠的 3x3 窗口
    config.collocation = struct( ...
        'windowSize', 3, ...
        'computeSampleMeanTB', false, ...
        'parameterWeighting', "none", ...
        'subgridDivisions', 5, ...
        'distancePower', 2, ...
        'centerStride', 3, ...
        'centerPhase', [2 2]);

    %% 5. 表面温度输入
    % source="fixed" 使用 fixedC；source="oib_kt19" 逐点读取 OIB 字段。
    % KT19 低于 Cox--Weeks 适用下限时，真实温度廓线仍用 KT19，只有进入
    % 卤水经验式的温度由 oibBrineFloorC 保护。
    config.temperature = struct( ...
        'source', "fixed", ...
        'fixedC', -30, ...
        'oibField', "KT19_surf", ...
        'oibBrineFloorC', -30);

    %% 6. L 波段前向模型
    % Vb 按 Cox--Weeks 计算；当前冻结默认不在进入 Vant 介电经验式前截断。
    % 超过 70 permille 时保留原值并由 diagnostics 标记；截断仅作敏感性试验。
    config.model = struct( ...
        'surfaceTempC', -30, ...
        'waterTempC', -1.8, ...
        'waterSalinity', 33, ...
        'rhoWater', 1024, ...
        'rhoIce', 915, ...
        'rhoSnow', 320, ...
        'nIceLayers', 20, ...
        'nSnowLayers', 1, ...
        'frequencyHz', 1.4e9, ...
        'incidenceAnglesDeg', 0:1:40, ...
        'includeCosmic', true, ...
        'cosmicTBK', 2.7, ...
        'atmosphereTBK', 0, ...
        'tbOffsetK', 0, ...
        'snowDensityKgM3', 320, ...
        'snowConductivity', 0.31, ...
        'fyiMinSalinityPpt', 1.5, ...
        'maxBrinePermille', 70, ...
        'limitBrinePermittivity', false, ...
        'allowColdBrineExtrapolation', false, ...
        'brineColdExtrapolationMode', "none", ...
