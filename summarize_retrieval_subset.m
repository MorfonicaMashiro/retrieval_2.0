function metricSummary = summarize_retrieval_subset( ...
        results, subsetMask, nearTB, nearTbThresholdK)
%SUMMARIZE_RETRIEVAL_SUBSET 汇总指定样本子集的亮温与反演验证指标。

    arguments
        results table
        subsetMask (:,1) logical
        nearTB (:,1) logical
        nearTbThresholdK (1,1) double {mustBePositive} = 1.5
    end
    if height(results) ~= numel(subsetMask) || height(results) ~= numel(nearTB)
        error('summarize_retrieval_subset:MaskSize', ...
            '筛选掩膜与结果表行数不一致。');
    end

    restricted = subsetMask & nearTB;
    nearPrefix = "|TB误差|<=" + string(nearTbThresholdK) + " K：";
    metricNames = ["TB：全部配对"; ...
        "TB+FBice：冰厚"; "TB+FBice：雪深"; ...
        "TB+FBsnow：冰厚"; "TB+FBsnow：雪深"; ...
        nearPrefix + "TB+FBice 冰厚"; ...
        nearPrefix + "TB+FBice 雪深"; ...
        nearPrefix + "TB+FBsnow 冰厚"; ...
        nearPrefix + "TB+FBsnow 雪深"];
    metricFits = { ...
        fit_retrieval(results.TB(subsetMask), results.tbFromOIB(subsetMask)); ...
        fit_retrieval(results.hi(subsetMask), results.hiRadar(subsetMask)); ...
        fit_retrieval(results.hs(subsetMask), results.hsRadar(subsetMask)); ...
        fit_retrieval(results.hi(subsetMask), results.hiLaser(subsetMask)); ...
        fit_retrieval(results.hs(subsetMask), results.hsLaser(subsetMask)); ...
        fit_retrieval(results.hi(restricted), results.hiRadar(restricted)); ...
        fit_retrieval(results.hs(restricted), results.hsRadar(restricted)); ...
        fit_retrieval(results.hi(restricted), results.hiLaser(restricted)); ...
        fit_retrieval(results.hs(restricted), results.hsLaser(restricted))};

    nMetrics = numel(metricNames);
    metricSummary = table(metricNames, zeros(nMetrics,1), ...
        nan(nMetrics,1), nan(nMetrics,1), nan(nMetrics,1), ...
        nan(nMetrics,1), nan(nMetrics,1), nan(nMetrics,1), ...
        'VariableNames', {'metric','n','correlation','rSquared','bias', ...
        'rmse','slope','intercept'});
    for metricIndex = 1:nMetrics
        currentFit = metricFits{metricIndex};
        metricSummary.n(metricIndex) = currentFit.n;
        metricSummary.correlation(metricIndex) = currentFit.correlation;
        metricSummary.rSquared(metricIndex) = currentFit.rSquared;
        metricSummary.bias(metricIndex) = currentFit.bias;
        metricSummary.rmse(metricIndex) = currentFit.rmse;
        metricSummary.slope(metricIndex) = currentFit.slope;
        metricSummary.intercept(metricIndex) = currentFit.intercept;
    end
end
