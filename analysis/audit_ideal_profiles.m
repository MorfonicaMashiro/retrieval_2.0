function audit = audit_ideal_profiles(outputDirectory)
%AUDIT_IDEAL_PROFILES 八场景温盐与物理界面审查。
%   导出层中点温盐/介电与物理界面两侧介电，逐项检查边界温度、热通量、
%   层中点位置和盐度公式。比较两种界面 Fresnel 口径，并运行两条反演
%   路线的八场景闭环。不会读取 OIB/SMOS 或运行层数/参数敏感性分析。

    if nargin < 1 || strlength(string(outputDirectory)) == 0
        outputDirectory = fullfile(fileparts(mfilename('fullpath')), ...
            'profile_interface_audit');
    end
    if ~isfolder(outputDirectory), mkdir(outputDirectory); end
    matlabRoot = fileparts(fileparts(mfilename('fullpath')));
    addpath(matlabRoot);
    data = readtable(fullfile(matlabRoot, 'processed', ...
        'tb_forward_table1_validation.csv'));
    assert(height(data) == 8, '表 1 场景数据应有八行。');
    model = struct('surfaceTempC', -30, 'waterTempC', -1.8, ...
        'waterSalinity', 33, 'rhoWater', 1024, ...
        'rhoIce', 915, 'rhoSnow', 320);
    boundaryModel = model;
    boundaryModel.interfacePermittivityMode = "boundary";

    tbMidpoint = nan(8,1); tbBoundary = nan(8,1);
    interfaceTemp = nan(8,1); kIce = nan(8,1);
    heatFlux = nan(8,1); topSalinity = nan(8,1);
    bottomSalinity = nan(8,1); maxBrine = nan(8,1);
    layerRows = cell(0,11);
    interfaceRows = cell(0,7);
    for k = 1:8
        scenario = string(data.scenario(k));
        [tbMidpoint(k), detail] = tb_forward( ...
            data.hi(k), data.hs(k), data.isMYI(k), model);
        tbBoundary(k) = tb_forward( ...
            data.hi(k), data.hs(k), data.isMYI(k), boundaryModel);
        profile = detail.profile;
        boundary = detail.boundary;
        nIce = detail.nIceLayers;
        nSnow = detail.nSnowLayers;

        % 独立使用边界条件和层中点坐标检查已实现的温度解。
        expectedFlux = (model.waterTempC - model.surfaceTempC) / ...
            (data.hs(k) / profile.snowConductivityWmK + ...
             data.hi(k) / profile.iceConductivityWmK);
        expectedInterface = model.surfaceTempC + ...
            expectedFlux * data.hs(k) / profile.snowConductivityWmK;
        expectedIceDepth = ((1:nIce) - 0.5) * data.hi(k) / nIce;
        expectedSnowDepth = ((1:nSnow) - 0.5) * data.hs(k) / nSnow;
        assert(abs(profile.heatFluxWm2 - expectedFlux) < 1e-10);
        assert(abs(profile.interfaceTemperatureC - expectedInterface) < 1e-10);
        assert(abs(profile.snowBottomTemperatureC - ...
            profile.interfaceTemperatureC) < 1e-10);
        assert(abs(profile.iceBottomTemperatureC - ...
            model.waterTempC) < 1e-10);
        assert(max(abs(profile.iceLayerMidDepthM - expectedIceDepth)) < 1e-12);
        assert(max(abs(profile.snowLayerMidDepthM - expectedSnowDepth)) < 1e-12);
        assert(max(abs(profile.iceLayerTemperatureC - ...
            (expectedInterface + expectedFlux .* expectedIceDepth / ...
            profile.iceConductivityWmK))) < 1e-10);
        assert(max(abs(profile.snowLayerTemperatureC - ...
            (model.surfaceTempC + expectedFlux .* expectedSnowDepth / ...
            profile.snowConductivityWmK))) < 1e-10);
        assert(all(diff(profile.iceLayerTemperatureC) > 0));

        if data.isMYI(k)
            z = ((1:nIce) - 0.5) / nIce;
            expectedSalinity = 1.6 .* ...
                (1 - cos(pi .* z .^ (0.407 ./ (z + 0.573))));
            assert(max(abs(profile.iceLayerSalinityPpt - ...
                expectedSalinity)) < 1e-12);
            assert(all(diff(profile.iceLayerSalinityPpt) > 0));
            assert(profile.iceTopSalinityPpt == 0 && ...
                abs(profile.iceBottomSalinityPpt - 3.2) < 1e-12);
        else
            expectedSalinity = max(1.5, ...
                6.08 * exp(-5.81 * data.hi(k)) + ...
                7.409 * exp(-0.5228 * data.hi(k)));
            assert(all(abs(profile.iceLayerSalinityPpt - ...
                expectedSalinity) < 1e-12));
            assert(abs(profile.iceTopSalinityPpt - ...
                expectedSalinity) < 1e-12);
            assert(abs(profile.iceBottomSalinityPpt - ...
                expectedSalinity) < 1e-12);
        end
        assert(abs(tbMidpoint(k) - data.tbModel(k)) < 1e-9, ...
            '历史中点口径 TB 与先前八场景 CSV 不一致。');

        interfaceTemp(k) = profile.interfaceTemperatureC;
        kIce(k) = profile.iceConductivityWmK;
        heatFlux(k) = profile.heatFluxWm2;
        topSalinity(k) = profile.iceTopSalinityPpt;
        bottomSalinity(k) = profile.iceBottomSalinityPpt;
        maxBrine(k) = detail.maxBrineVolumePermille;

        for j = 1:nSnow
            epsValue = profile.snowLayerPermittivity(j);
            layerRows(end+1,:) = {scenario, logical(data.isMYI(k)), ...
                "snow", j, profile.snowLayerMidDepthM(j), ...
                profile.snowLayerTemperatureC(j), NaN, NaN, NaN, ...
                real(epsValue), imag(epsValue)}; %#ok<AGROW>
        end
        for j = 1:nIce
            epsValue = profile.iceLayerPermittivity(j);
            layerRows(end+1,:) = {scenario, logical(data.isMYI(k)), ...
                "ice", j, profile.iceLayerMidDepthM(j), ...
                profile.iceLayerTemperatureC(j), ...
                profile.iceLayerSalinityPpt(j), ...
                profile.iceLayerBrineRawPermille(j), ...
                profile.iceLayerBrineUsedPermille(j), ...
                real(epsValue), imag(epsValue)}; %#ok<AGROW>
        end
        interfaceRows(end+1,:) = {scenario, "air/snow", "snow side", ...
            model.surfaceTempC, NaN, real(boundary.snowTop), ...
            imag(boundary.snowTop)}; %#ok<AGROW>
        interfaceRows(end+1,:) = {scenario, "snow/ice", "snow side", ...
            interfaceTemp(k), NaN, real(boundary.snowBottom), ...
            imag(boundary.snowBottom)}; %#ok<AGROW>
        interfaceRows(end+1,:) = {scenario, "snow/ice", "ice side", ...
            interfaceTemp(k), topSalinity(k), real(boundary.iceTop), ...
            imag(boundary.iceTop)}; %#ok<AGROW>
        interfaceRows(end+1,:) = {scenario, "ice/water", "ice side", ...
            model.waterTempC, bottomSalinity(k), ...
            real(boundary.iceBottom), imag(boundary.iceBottom)}; %#ok<AGROW>
        interfaceRows(end+1,:) = {scenario, "ice/water", "water side", ...
            model.waterTempC, model.waterSalinity, ...
            real(boundary.iceWaterLower), ...
            imag(boundary.iceWaterLower)}; %#ok<AGROW>
    end

    comparison = table(string(data.scenario), logical(data.isMYI), ...
        data.hi, data.hs, data.tbPaper, tbMidpoint, tbBoundary, ...
        tbMidpoint-data.tbPaper, tbBoundary-data.tbPaper, ...
        tbBoundary-tbMidpoint, interfaceTemp, kIce, heatFlux, ...
        topSalinity, bottomSalinity, maxBrine, ...
        'VariableNames', {'scenario','isMYI','hiM','hsM','tbPaperK', ...
        'tbMidpointK','tbBoundaryK','midpointMinusPaperK', ...
        'boundaryMinusPaperK','boundaryMinusMidpointK', ...
        'snowIceInterfaceTempC','iceConductivityWmK','heatFluxWm2', ...
        'iceTopSalinityPpt','iceBottomSalinityPpt', ...
        'maxLayerBrineRawPermille'});
    layers = cell2table(layerRows, 'VariableNames', ...
        {'scenario','isMYI','material','layerIndex', ...
        'depthFromMaterialTopM','temperatureC','salinityPpt', ...
        'brineRawPermille','brineUsedPermille', ...
        'epsilonReal','epsilonImag'});
    interfaces = cell2table(interfaceRows, 'VariableNames', ...
        {'scenario','interface','side','temperatureC','salinityPpt', ...
        'epsilonReal','epsilonImag'});
    writetable(comparison, fullfile(outputDirectory, ...
        'eight_scenario_temperature_interface_tb.csv'));
    writetable(layers, fullfile(outputDirectory, ...
        'eight_scenario_layer_profiles.csv'));
    writetable(interfaces, fullfile(outputDirectory, ...
        'eight_scenario_physical_interfaces.csv'));

    midpointDir = fullfile(outputDirectory, 'midpoint_closure');
    boundaryDir = fullfile(outputDirectory, 'boundary_closure');
    midpointClosure = validate_inversion_closure(midpointDir, ...
        struct('interfacePermittivityMode', "midpoint"));
    boundaryClosure = validate_inversion_closure(boundaryDir, ...
        struct('interfacePermittivityMode', "boundary"));
    audit = struct('comparison',comparison,'layers',layers, ...
        'interfaces',interfaces,'midpointClosure',midpointClosure, ...
        'boundaryClosure',boundaryClosure);
    fprintf('八场景温盐和物理界面审查通过；结果目录：%s\n', outputDirectory);
end
