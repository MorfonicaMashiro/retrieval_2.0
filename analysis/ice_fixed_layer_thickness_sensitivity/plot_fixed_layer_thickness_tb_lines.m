function pngFile = plot_fixed_layer_thickness_tb_lines()
%PLOT_FIXED_LAYER_THICKNESS_TB_LINES 不同冰层离散方式的八场景亮温折线图。
%   只读取既有敏感性结果，不重算前向模型。I-IV 为 FYI，V-VIII 为 MYI；
%   连线只在同一冰型内部连接，避免暗示跨冰型连续变化。仅输出 PNG。

    testRoot = fileparts(mfilename('fullpath'));
    sourceFile = fullfile(testRoot, 'results', ...
        'fixed_ice_layer_thickness_1_5_10cm_wide.csv');
    figureRoot = fullfile(testRoot, 'figures');
    if ~isfolder(figureRoot), mkdir(figureRoot); end

    data = readtable(sourceFile, 'TextType', 'string');
    required = {'scenario','tbPaperK','tb20LayerK', ...
        'tb_01cm_K','tb_05cm_K','tb_10cm_K'};
    assert(height(data) == 8 && all(ismember(required, ...
        data.Properties.VariableNames)), ...
        '需要八个场景及论文、20层、1/5/10 cm 的完整亮温结果。');

    fontName = 'Microsoft YaHei';
    colors = [0.0000 0.0000 0.0000; ... % 论文：黑
              0.8000 0.4745 0.6549; ... % 20层：紫
              0.0000 0.4470 0.6980; ... % 1 cm：蓝
              0.9020 0.6240 0.0000; ... % 5 cm：橙
              0.0000 0.6196 0.4510];    % 10 cm：绿
    lineStyles = {'-','--','-.','-',':'};
    markers = {'o','d','^','s','v'};
    labels = {'论文亮温','固定 20 层','固定 1 cm', ...
        '固定 5 cm','固定 10 cm'};
    values = [data.tbPaperK, data.tb20LayerK, data.tb_01cm_K, ...
        data.tb_05cm_K, data.tb_10cm_K];

    figureHandle = figure('Visible','off','Color','white', ...
        'Units','pixels','Position',[80 80 1600 720]);
    ax = axes(figureHandle);
    hold(ax,'on');

    x = (1:8)';
    lineHandles = gobjects(5,1);
    for seriesIndex = 1:5
        y = values(:,seriesIndex);
        lineHandles(seriesIndex) = plot(ax,x(1:4),y(1:4), ...
            'Color',colors(seriesIndex,:), ...
            'LineStyle',lineStyles{seriesIndex}, ...
            'LineWidth',2.2, ...
            'Marker',markers{seriesIndex}, ...
            'MarkerSize',7.5, ...
            'MarkerFaceColor','white', ...
            'MarkerEdgeColor',colors(seriesIndex,:), ...
            'DisplayName',labels{seriesIndex});
        plot(ax,x(5:8),y(5:8), ...
            'Color',colors(seriesIndex,:), ...
            'LineStyle',lineStyles{seriesIndex}, ...
            'LineWidth',2.2, ...
            'Marker',markers{seriesIndex}, ...
            'MarkerSize',7.5, ...
            'MarkerFaceColor','white', ...
            'MarkerEdgeColor',colors(seriesIndex,:), ...
            'HandleVisibility','off');
    end

    xline(ax,4.5,'k:','LineWidth',1.2,'HandleVisibility','off');
    text(ax,2.5,253.35,'FYI','HorizontalAlignment','center', ...
        'FontName',fontName,'FontSize',12,'FontWeight','bold', ...
        'Color',colors(3,:));
    text(ax,6.5,253.35,'MYI','HorizontalAlignment','center', ...
        'FontName',fontName,'FontSize',12,'FontWeight','bold', ...
        'Color',colors(4,:));

    xlim(ax,[0.6 8.4]);
    ylim(ax,[228 254]);
    xticks(ax,1:8);
    xticklabels(ax,string(data.scenario));
    yticks(ax,228:4:252);
    xlabel(ax,'论文场景','FontName',fontName,'FontSize',13);
    ylabel(ax,'亮温（K）','FontName',fontName,'FontSize',13);
    title(ax,'不同冰层离散方式的亮温对比', ...
        'FontName',fontName,'FontSize',16,'FontWeight','bold');
    subtitle(ax,'离散场景的连线仅用于同冰型内部视觉比较', ...
        'FontName',fontName,'FontSize',10);

    legend(ax,lineHandles,labels,'Location','northoutside', ...
        'Orientation','horizontal','NumColumns',5,'Box','off', ...
        'FontName',fontName,'FontSize',10);
    grid(ax,'on');
    ax.XGrid = 'off';
    ax.YGrid = 'on';
    ax.GridColor = [0.82 0.90 0.95];
    ax.GridAlpha = 0.75;
    ax.FontName = fontName;
    ax.FontSize = 11;
    ax.LineWidth = 1.0;
    ax.Box = 'off';
    text(ax,0.995,0.02, ...
        '纵轴截取 228–254 K，以分辨分层造成的亮温差异。', ...
        'Units','normalized','HorizontalAlignment','right', ...
        'VerticalAlignment','bottom','FontName',fontName, ...
        'FontSize',9,'Color','black');

    pngFile = fullfile(figureRoot, ...
        'fixed_layer_thickness_tb_lines.png');
    if isfile(pngFile), delete(pngFile); end
    exportgraphics(figureHandle,pngFile,'Resolution',300);
    close(figureHandle);
    fprintf('亮温折线图已保存：%s\n',pngFile);
end
