function outputs = plot_scenario_viii_layer_contributions(outputDirectory)
%PLOT_SCENARIO_VIII_LAYER_CONTRIBUTIONS Plot layer and five-layer blocks.

    if nargin < 1 || strlength(string(outputDirectory)) == 0
        outputDirectory = fullfile(fileparts(mfilename('fullpath')), ...
            'layer_contribution_audit');
    end
    layers = readtable(fullfile(outputDirectory, ...
        'scenario_viii_layer_contributions.csv'), 'TextType', 'string');
    blocks = readtable(fullfile(outputDirectory, ...
        'scenario_viii_five_layer_blocks.csv'), 'TextType', 'string');
    external = readtable(fullfile(outputDirectory, ...
        'scenario_viii_external_contributions.csv'), 'TextType', 'string');

    fontName = 'Microsoft YaHei';
    colors = [0.0000 0.4470 0.6980; ... % blue
              0.9020 0.6240 0.0000; ... % orange
              0.0000 0.6196 0.4510; ... % green
              0.8000 0.4745 0.6549];    % purple
    figureHandle = figure('Color','w','Units','inches', ...
        'Position',[1 1 7.2 3.65]);
    layout = tiledlayout(figureHandle,1,2,'TileSpacing','compact', ...
        'Padding','compact');
    title(layout, ...
        '场景 VIII：5 m 多年冰与 0.4 m 雪层的亮温贡献分解（总计 246.863 K）', ...
        'FontName',fontName,'FontSize',10,'FontWeight','bold');

    ax1 = nexttile(layout,1);
    hold(ax1,'on');
    ice = layers.material == "ice";
    snow = layers.material == "snow";
    semilogx(ax1,layers.surfaceContributionK(ice),layers.depthCenterM(ice), ...
        '-o','Color',colors(1,:),'LineWidth',1.2,'MarkerSize',3.5, ...
        'MarkerFaceColor',colors(1,:),'DisplayName','冰层（逐层）');
    scatter(ax1,layers.surfaceContributionK(snow),layers.depthCenterM(snow), ...
        30,'s','filled','MarkerFaceColor',colors(2,:), ...
        'DisplayName','雪层');
    waterContribution = external.surfaceContributionK( ...
        external.component == "water");
    scatter(ax1,waterContribution,5.4,32,'^','filled', ...
        'MarkerFaceColor',colors(3,:),'DisplayName','海水背景');
    interfaceLine = yline(ax1,0.4,'--','雪-冰界面','Color',[0.45 0.45 0.45], ...
        'FontName',fontName,'FontSize',7,'LabelVerticalAlignment','bottom');
    interfaceLine.HandleVisibility = 'off';
    set(ax1,'YDir','reverse','XScale','log','XLim',[0.1 35], ...
        'YLim',[0 5.55],'FontName',fontName,'FontSize',7, ...
        'Box','off','XGrid','on','YGrid','off');
    ax1.XMinorGrid = 'off';
    xlabel(ax1,'到达空气侧的平均亮温贡献（K，对数轴）', ...
        'FontName',fontName,'FontSize',8);
    ylabel(ax1,'距雪表面深度（m）','FontName',fontName,'FontSize',8);
    title(ax1,'逐层最终贡献','FontName',fontName,'FontSize',9);
    legend(ax1,'Location','southwest','Box','off','FontName',fontName, ...
        'FontSize',7);
    text(ax1,-0.10,1.01,'a','Units','normalized','FontName','Arial', ...
        'FontWeight','bold','FontSize',9);

    ax2 = nexttile(layout,2);
    blockColors = [0.60 0.60 0.60; ...
                   0.337 0.706 0.914; ...
                   0.000 0.447 0.698; ...
                   0.298 0.447 0.690; ...
                   0.424 0.557 0.749; ...
                   colors(3,:); colors(4,:)];
    bars = barh(ax2,blocks.surfaceContributionK,'FaceColor','flat', ...
        'EdgeColor','w','LineWidth',0.5);
    bars.CData = blockColors;
    labels = ["雪层","冰层 1-5","冰层 6-10","冰层 11-15", ...
        "冰层 16-20","海水","宇宙背景"];
    set(ax2,'YDir','reverse','YTick',1:height(blocks),'YTickLabel',labels, ...
        'XLim',[0 150],'FontName',fontName,'FontSize',7,'Box','off', ...
        'XGrid','on','YGrid','off');
    xlabel(ax2,'到达空气侧的平均亮温贡献（K）', ...
        'FontName',fontName,'FontSize',8);
    title(ax2,'每5个冰层的精确分块贡献','FontName',fontName,'FontSize',9);
    for index = 1:height(blocks)
        text(ax2,blocks.surfaceContributionK(index)+2,index, ...
            sprintf('%.2f K  (%.1f%%)',blocks.surfaceContributionK(index), ...
            blocks.fractionOfTotalTBPercent(index)), ...
            'VerticalAlignment','middle','FontName',fontName,'FontSize',6.8);
    end
    text(ax2,-0.10,1.01,'b','Units','normalized','FontName','Arial', ...
        'FontWeight','bold','FontSize',9);

    pngPath = fullfile(outputDirectory, ...
        'scenario_viii_layer_contributions.png');
    pdfPath = fullfile(outputDirectory, ...
        'scenario_viii_layer_contributions.pdf');
    exportgraphics(figureHandle,pngPath,'Resolution',300);
    if isfile(pdfPath), delete(pdfPath); end
    exportgraphics(figureHandle,pdfPath,'ContentType','image', ...
        'Resolution',300);
    close(figureHandle);

    outputs = struct('png',pngPath,'pdf',pdfPath);
end
