function [results, metricSummary, summary] = ...
        run_stride3_pointwise_freeboard_inversion( ...
        targetDays, outputStem, maxPairsPerDay)
%RUN_STRIDE3_POINTWISE_FREEBOARD_INVERSION 逐点干舷与逐点 TB 等权联合反演。
%   与旧的前向诊断脚本不同，本入口不复用平均干舷反演根。

    if nargin < 1, targetDays = datetime.empty(0,1); end
    if nargin < 2
        outputStem = "stride3_pointwise_uniform_vb_uncapped_fixed_temp_2012_2015";
    end
    if nargin < 3, maxPairsPerDay = Inf; end
    routeRoot = fileparts(mfilename('fullpath'));
    commonRoot = fullfile(fileparts(routeRoot), 'common');
    addpath(commonRoot);
    route = struct('name', "pointwise_uniform", ...
        'routeRoot', routeRoot, 'weightingMode', "uniform", ...
        'subgridDivisions', 5, ...
        'maxPairsPerDay', maxPairsPerDay, ...
        'defaultOutputStem', ...
        "stride3_pointwise_uniform_vb_uncapped_fixed_temp_2012_2015", ...
        'contextLabel', "逐点干舷→逐点冰厚/雪深→逐点 TB→算术平均");
    [results, metricSummary, summary] = ...
        run_pointwise_freeboard_route(route, targetDays, outputStem);
end
