function verify_pointwise_freeboard_inversion()
%VERIFY_POINTWISE_FREEBOARD_INVERSION 验证逐点观测算子的自闭环。

    routeRoot = fileparts(mfilename('fullpath'));
    matlabRoot = fileparts(fileparts(fileparts(routeRoot)));
    commonRoot = fullfile(fileparts(routeRoot), 'common');
    addpath(matlabRoot, commonRoot);
    model = struct('surfaceTempC', -30, 'waterTempC', -1.8, ...
        'waterSalinity', 33, 'rhoWater', 1024, ...
        'rhoIce', 915, 'rhoSnow', 320, ...
        'radiativeTransferMode', "burke", ...
        'limitBrinePermittivity', false, ...
        'incidenceAnglesDeg', 0:10:40);
    hiTruth = [0.8; 1.1; 1.5];
    hsTruth = 0.10 * ones(size(hiTruth));
    weights = [1; 2; 1];
    tbSamples = tb_forward(hiTruth, hsTruth, false, model);
    tbObs = sum(weights .* tbSamples) / sum(weights);
    fbSnow = ((model.rhoWater-model.rhoIce).*hiTruth + ...
        (model.rhoWater-model.rhoSnow).*hsTruth) ./ model.rhoWater;
    fbIce = ((model.rhoWater-model.rhoIce).*hiTruth - ...
        model.rhoSnow.*hsTruth) ./ model.rhoWater;
    options = struct('scanStepM', 0.02, 'initialStepM', 0.02, ...
        'tbToleranceK', 1e-4, 'snowToleranceM', 1e-7);
    [snowSolutions, snowInfo] = invert_pointwise_freeboard_pair( ...
        tbObs, fbSnow, "snow", false, model, @tb_forward, weights, options);
    [iceSolutions, iceInfo] = invert_pointwise_freeboard_pair( ...
        tbObs, fbIce, "ice", false, model, @tb_forward, weights, options);
    assert(snowInfo.rootCount >= 1 && iceInfo.rootCount >= 1, ...
        '逐点自闭环没有找到真值分支。');
    expectedHi = sum(weights .* hiTruth) / sum(weights);
    snowErrors = hypot([snowSolutions.hi]-expectedHi, ...
        [snowSolutions.hs]-hsTruth(1));
    iceErrors = hypot([iceSolutions.hi]-expectedHi, ...
        [iceSolutions.hs]-hsTruth(1));
    assert(min(snowErrors) < 2e-4, 'FBsnow 逐点自闭环未恢复真值。');
    assert(min(iceErrors) < 2e-4, 'FBice 逐点自闭环未恢复真值。');
    fprintf('逐点干舷联合反演自闭环通过：FBice 与 FBsnow 均恢复真值。\n');
end
