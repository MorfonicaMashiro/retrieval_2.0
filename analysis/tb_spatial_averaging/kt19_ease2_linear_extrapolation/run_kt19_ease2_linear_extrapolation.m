function [pairs, metrics, summary] = ...
        run_kt19_ease2_linear_extrapolation(targetDays, outputStem)
%RUN_KT19_EASE2_LINEAR_EXTRAPOLATION 全量 OIB KT19--EASE2 前向试验。
%   保持步长 3、相位 [2 2]、参数先平均后算 TB、Burke、20 层冰和
%   1 层雪。OIB KT19_surf 作为真实表温；Cox--Weeks F1 在 -30 degC
%   以下采用 -30 degC 处切线线性外推。Vb>70 permille 只标记、不截断。

    if nargin < 1, targetDays = datetime.empty(0,1); end
    if nargin < 2 || strlength(string(outputStem)) == 0
        outputStem = "kt19_ease2_linear_extrapolation_2012_2015";
    end
    targetDays = dateshift(datetime(targetDays(:)), 'start', 'day');
    outputStem = string(outputStem);

    branchRoot = fileparts(mfilename('fullpath'));
    matlabRoot = fileparts(fileparts(fileparts(branchRoot)));
    workspaceRoot = fileparts(matlabRoot);
    dataRoot = fullfile(workspaceRoot, 'data');
    resultRoot = fullfile(branchRoot, 'results');
    figureRoot = fullfile(branchRoot, 'figures');
    addpath(matlabRoot, fullfile(matlabRoot, 'readdata'), ...
        fullfile(matlabRoot, 'plot'), branchRoot);
    if ~isfolder(resultRoot), mkdir(resultRoot); end
    if ~isfolder(figureRoot), mkdir(figureRoot); end

    overrides = struct( ...
        'data', struct('gridVersion', "EASE2"), ...
        'temperature', struct('source', "oib_kt19", ...
            'oibBrineFloorC', NaN), ...
        'model', struct('brineColdExtrapolationMode', ...
            "linear_below_minus30", ...
            'allowColdBrineExtrapolation', false, ...
            'limitBrinePermittivity', false), ...
        'output', struct('variantTag', ...
            "ease2_kt19_cold_linear_vb_uncapped_stride3"));
    config = retrieval_config(overrides);
    model = config.model;
    fixedModel = model;
    fixedModel.surfaceTempC = config.temperature.fixedC;
    fixedModel.brineTemperatureFloorC = NaN;
    fixedModel.brineColdExtrapolationMode = "none";
    fixedModel.allowColdBrineExtrapolation = false;

    flightFiles = find_flight_files(dataRoot, targetDays);
    if isempty(flightFiles)
        error('run_kt19_ease2_linear_extrapolation:NoFlights', ...
            '指定日期没有找到 2012/2015 OIB 飞行文件。');
    end
    pairs = table();
    summary = table();
    outputFile = fullfile(resultRoot, outputStem + ".mat");
    totalTimer = tic;
    for flightIndex = 1:height(flightFiles)
        day = flightFiles.day(flightIndex);
        token = char(string(day, 'yyyyMMdd'));
        smosFile = fullfile(dataRoot, 'smos', char(string(year(day))), ...
            ['SMOS_TB_north_' token '.nc']);
        if ~isfile(smosFile)
            error('run_kt19_ease2_linear_extrapolation:MissingSMOS', ...
                '%s 缺少同日 SMOS 文件：%s', token, smosFile);
        end
        oib = read_oib(char(flightFiles.path(flightIndex)));
        smosEase = grid_resampling.regrid_smos_to_ease( ...
            read_smos(smosFile), "EASE2");
        [dailyPairs, stats] = collocate_day(oib, smosEase, day, config);

        [kt19TB, brineTemperatureExtrapolated, ...
            brineValidityExceeded, maxBrineVolumePermille] = ...
            evaluate_pairs(dailyPairs, model, true);
        if max(abs(kt19TB - dailyPairs.TBOIBMeanParameters), ...
                [], 'omitnan') > 1e-10
            error('run_kt19_ease2_linear_extrapolation:ForwardMismatch', ...
                '重算 KT19 TB 与 collocate_day 结果不一致。');
        end
        fixedTB = evaluate_pairs(dailyPairs, fixedModel, false);
        kt19MinusFixedK = kt19TB - fixedTB;
        dailyPairs = addvars(dailyPairs, fixedTB, kt19TB, ...
            kt19MinusFixedK, brineTemperatureExtrapolated, ...
            maxBrineVolumePermille, brineValidityExceeded, ...
            'NewVariableNames', {'TBOIBFixedMinus30SameKT19', ...
            'TBOIBKT19Linear','TBKT19MinusFixedK', ...
            'brineTemperatureExtrapolated', ...
            'maxBrineVolumePermille','brineValidityExceeded'});
        pairs = [pairs; dailyPairs]; %#ok<AGROW>

        if isempty(dailyPairs)
            minimumMeanKT19C = NaN;
            medianMeanKT19C = NaN;
            maximumMeanKT19C = NaN;
        else
            minimumMeanKT19C = min( ...
                dailyPairs.surfaceTempC,[],'omitnan');
            medianMeanKT19C = median( ...
                dailyPairs.surfaceTempC,'omitnan');
            maximumMeanKT19C = max( ...
                dailyPairs.surfaceTempC,[],'omitnan');
        end

        summary = [summary; table(day, stats.rawPoints, ...
            stats.geometryQualityPoints, stats.temperatureRejectedPoints, ...
            stats.qualityPoints, stats.tbOverlapCells, ...
            stats.mixedTypeCells, height(dailyPairs), ...
            minimumMeanKT19C, medianMeanKT19C, maximumMeanKT19C, ...
            nnz(dailyPairs.surfaceTempC < -30), ...
            nnz(dailyPairs.surfaceTempC < -35), ...
            nnz(dailyPairs.surfaceTempC < -40), ...
            nnz(brineTemperatureExtrapolated), ...
            nnz(brineValidityExceeded), stats.forwardSeconds, ...
            'VariableNames', {'day','rawOIBPoints', ...
            'geometryQualityPoints','temperatureRejectedPoints', ...
            'validKT19OIBPoints','tbOverlapCells','mixedTypeCells', ...
            'matchedPairs','minimumMeanKT19C', ...
            'medianMeanKT19C','maximumMeanKT19C', ...
            'pairsMeanKT19BelowMinus30','pairsMeanKT19BelowMinus35', ...
            'pairsMeanKT19BelowMinus40','pairsUsingColdExtrapolation', ...
            'pairsVbAbove70','forwardSeconds'})]; %#ok<AGROW>

        save(outputFile, 'pairs', 'summary', 'config', 'model', ...
            'fixedModel', '-v7.3');
        elapsedMinutes = toc(totalTimer) / 60;
        etaMinutes = elapsedMinutes / flightIndex * ...
            (height(flightFiles) - flightIndex);
        fprintf(['[%d/%d] %s：EASE2 配对 %d，KT19拒绝 %d，' ...
            '冷端外推 %d，Vb>70‰ %d；累计 %.1f min，' ...
            '预计剩余 %.1f min。\n'], flightIndex, height(flightFiles), ...
            token, height(dailyPairs), stats.temperatureRejectedPoints, ...
            nnz(brineTemperatureExtrapolated), ...
            nnz(brineValidityExceeded), elapsedMinutes, etaMinutes);
    end

    pairs = sortrows(pairs, {'day','row','col'});
    summary = sortrows(summary, 'day');
    metrics = build_metrics(pairs);
    metricsByYear = build_metrics_by_year(pairs);
    method = struct( ...
        'grid', "EASE2-N 12.5 km", 'gridEpsg', 6931, ...
        'centerStride', 3, 'centerPhase', [2 2], ...
        'operator', "mean hi/hs/KT19 then one forward TB", ...
        'temperature', "OIB KT19_surf", ...
        'coldBrinePolicy', ...
        "Cox-Weeks F1 tangent-linear extrapolation below -30 C", ...
        'brinePermittivityPolicy', "flag above 70 permille; no cap", ...
        'radiativeTransfer', "Burke");
    save(outputFile, 'pairs', 'summary', 'metrics', 'metricsByYear', ...
        'method', 'config', 'model', 'fixedModel', ...
        '-v7.3');
    writetable(pairs, fullfile(resultRoot, outputStem + "_pairs.csv"));
    writetable(summary, fullfile(resultRoot, outputStem + "_summary.csv"));
    writetable(metrics, fullfile(resultRoot, outputStem + "_metrics.csv"));
    writetable(metricsByYear, fullfile(resultRoot, ...
        outputStem + "_metrics_by_year.csv"));

    plot_temperature_comparison(pairs, fullfile(figureRoot, ...
        outputStem + "_tb_comparison.png"));
    residualInput = table(pairs.TB, pairs.TBOIBKT19Linear, ...
        'VariableNames', {'TB','tbFromOIB'});
    plot_tb_residual_distribution(residualInput, fullfile(figureRoot, ...
        outputStem + "_residual_distribution.png"), ...
        "EASE2；步长3；OIB KT19；-30°C以下线性外推");

    representativeDays = [datetime(2012,3,22); datetime(2015,4,3)];
    availableDays = representativeDays(ismember(representativeDays,pairs.day));
    if ~isempty(availableDays)
        plot_kt19_oib_tb_ease2_maps(pairs, availableDays, ...
            fullfile(figureRoot, outputStem + ...
            "_representative_days_oib_tb_map.png"));
        for dayIndex = 1:numel(availableDays)
            token = string(availableDays(dayIndex), 'yyyyMMdd');
            plot_kt19_oib_tb_ease2_maps(pairs, availableDays(dayIndex), ...
                fullfile(figureRoot, outputStem + "_" + token + ...
                "_oib_tb_map.png"));
        end
    end
    fprintf('KT19--EASE2 全量前向试验完成：%d 条配对，%.1f min。\n%s\n', ...
        height(pairs), toc(totalTimer)/60, outputFile);
    disp(metrics);
    disp(metricsByYear);
end


function [tb, coldExtrapolated, validityExceeded, maxBrine] = ...
        evaluate_pairs(pairs, model, usePairSurfaceTemperature)
%EVALUATE_PAIRS 逐冰型批量前向，并显式选择是否使用逐配对表温。
%   表温来源由调用者直接指定，不能再借用低温外推开关间接判断。
    n = height(pairs);
    tb = nan(n,1);
    coldExtrapolated = false(n,1);
    validityExceeded = false(n,1);
    maxBrine = nan(n,1);
    for iceType = [false true]
        selected = logical(pairs.isMYI) == iceType;
        if ~any(selected), continue; end
        currentModel = model;
        if usePairSurfaceTemperature && ...
                ismember('surfaceTempC', pairs.Properties.VariableNames)
            currentModel.surfaceTempC = pairs.surfaceTempC(selected);
        end
        [tb(selected), currentDiagnostics] = tb_forward( ...
            pairs.hi(selected), pairs.hs(selected), iceType, currentModel);
        coldExtrapolated(selected) = reshape( ...
            [currentDiagnostics.brineTemperatureExtrapolated], [], 1);
        validityExceeded(selected) = reshape( ...
            [currentDiagnostics.brineValidityExceeded], [], 1);
        maxBrine(selected) = reshape( ...
            [currentDiagnostics.maxBrineVolumePermille], [], 1);
    end
end


function metrics = build_metrics(pairs)
    names = ["固定-30°C：同一KT19有效样本"; ...
        "OIB KT19：-30°C以下F1线性外推"];
    modeled = {pairs.TBOIBFixedMinus30SameKT19; ...
        pairs.TBOIBKT19Linear};
    metrics = table();
    for index = 1:numel(modeled)
        fit = fit_retrieval(pairs.TB, modeled{index});
        current = table(names(index), fit.n, fit.correlation, ...
            fit.rSquared, fit.bias, fit.rmse, fit.slope, fit.intercept, ...
            'VariableNames', {'metric','n','correlation','rSquared', ...
            'bias','rmse','slope','intercept'});
        metrics = [metrics; current]; %#ok<AGROW>
    end
end


function metricsByYear = build_metrics_by_year(pairs)
    years = unique(year(pairs.day)).';
    metricsByYear = table();
    for currentYear = years
        selected = year(pairs.day) == currentYear;
        current = build_metrics(pairs(selected,:));
        current = addvars(current, repmat(currentYear,height(current),1), ...
            'Before', 1, 'NewVariableNames', 'year');
        metricsByYear = [metricsByYear; current]; %#ok<AGROW>
    end
end


function plot_temperature_comparison(pairs, pngPath)
    modeled = {pairs.TBOIBFixedMinus30SameKT19, ...
        pairs.TBOIBKT19Linear};
    titles = {'固定 −30°C：同一 KT19 有效样本', ...
        'OIB KT19：冷端线性外推'};
    colors = [0.00 0.45 0.70; 0.90 0.62 0.00];
    figureHandle = figure('Visible','off','Color','w', ...
        'Position',[80 80 1120 520]);
    layout = tiledlayout(figureHandle,1,2, ...
        'TileSpacing','compact','Padding','compact');
    title(layout,'EASE2 下 OIB 表面温度输入对前向亮温的影响', ...
        'FontName','Microsoft YaHei','FontWeight','bold');
    for panel = 1:2
        ax = nexttile(layout);
        valid = isfinite(pairs.TB) & isfinite(modeled{panel});
        scatter(ax,pairs.TB(valid),modeled{panel}(valid),20, ...
            colors(panel,:),'filled','MarkerFaceAlpha',0.52); hold(ax,'on');
        bounds = [min([pairs.TB(valid); modeled{panel}(valid)]), ...
            max([pairs.TB(valid); modeled{panel}(valid)])];
        plot(ax,bounds,bounds,'-','Color',[0.80 0.20 0.15], ...
            'LineWidth',1.3);
        fit = fit_retrieval(pairs.TB(valid),modeled{panel}(valid));
        text(ax,0.04,0.96,sprintf(['n=%d  RMSE=%.2f K\n' ...
            'Bias=%+.2f K  R^2=%.2f'],fit.n,fit.rmse,fit.bias,fit.rSquared), ...
            'Units','normalized','VerticalAlignment','top', ...
            'FontName','Microsoft YaHei','BackgroundColor','w','Margin',4);
        xlim(ax,bounds); ylim(ax,bounds); axis(ax,'square'); grid(ax,'on');
        xlabel(ax,'SMOS 观测亮温 (K)');
        ylabel(ax,'OIB 模拟亮温 (K)');
        title(ax,titles{panel}); ax.FontName='Microsoft YaHei';
    end
    exportgraphics(figureHandle,pngPath,'Resolution',300);
    close(figureHandle);
end


function flightFiles = find_flight_files(dataRoot, targetDays)
    specifications = { ...
        fullfile(dataRoot,'OIB','IDCSI4_L4','2012'), 'IDCSI4_*.txt'; ...
        fullfile(dataRoot,'OIB','NSIDC-0708_QuickLook','2015_GR_NASA'), ...
        'OIB_*_IDCSI2*.txt'};
    days = datetime.empty(0,1); paths = strings(0,1);
    for specificationIndex = 1:size(specifications,1)
        files = dir(fullfile(specifications{specificationIndex,1}, ...
            specifications{specificationIndex,2}));
        for fileIndex = 1:numel(files)
            token = regexp(files(fileIndex).name,'(\d{8})','match','once');
            day = datetime(token,'InputFormat','yyyyMMdd');
            if isempty(targetDays) || ismember(day,targetDays)
                days(end+1,1) = day; %#ok<AGROW>
                paths(end+1,1) = string(fullfile( ...
                    files(fileIndex).folder,files(fileIndex).name)); %#ok<AGROW>
            end
        end
    end
    flightFiles = sortrows(table(days,paths, ...
        'VariableNames',{'day','path'}),'day');
end
