function [comparison, diagnostics] = compare_stride3_averaging_results()
%COMPARE_STRIDE3_AVERAGING_RESULTS 对比参数先平均与逐样本 TB 先计算。
%   主对照固定使用相同的 733 个步长 3 配对；同时附上论文报告值和历史
%   步长 1 结果。输出宽表、分组诊断表和同轴散点/差值分布图。

    comparisonRoot = fileparts(mfilename('fullpath'));
    matlabRoot = fileparts(fileparts(fileparts(comparisonRoot)));
    resultRoot = fullfile(comparisonRoot, 'results');
    figureRoot = fullfile(comparisonRoot, 'figures');
    addpath(matlabRoot);
    if ~isfolder(resultRoot), mkdir(resultRoot); end
    if ~isfolder(figureRoot), mkdir(figureRoot); end

    parameterFile = fullfile(matlabRoot, 'analysis', ...
        'tb_spatial_averaging', 'baseline_parameter_mean_stride3', ...
        'results', 'stride3_parameter_mean_2012_2015_metrics.csv');
    sampleRoot = fullfile(matlabRoot, 'analysis', ...
        'tb_spatial_averaging', 'operator_2_sample_tb_mean', ...
        'results', 'stride3');
    sampleMetricFile = fullfile(sampleRoot, ...
        'stride3_sample_tb_mean_2012_2015_metrics.csv');
    sampleMatFile = fullfile(sampleRoot, ...
        'stride3_sample_tb_mean_2012_2015.mat');
    historicalFile = fullfile(matlabRoot, 'figures', ...
        'inversion_2012_2015_only', 'metrics_2012_2015_only.csv');
    requiredFiles = {parameterFile, sampleMetricFile, ...
        sampleMatFile, historicalFile};
    if ~all(cellfun(@isfile, requiredFiles))
        error('compare_stride3_averaging_results:MissingInput', ...
            '缺少参数平均、逐样本平均或历史对照结果。');
    end

    parameter = readtable(parameterFile, 'TextType', 'string');
    sample = readtable(sampleMetricFile, 'TextType', 'string');
    historical = readtable(historicalFile, 'TextType', 'string');
    if ~isequal(parameter.metric, sample.metric)
        error('compare_stride3_averaging_results:MetricOrder', ...
            '两个步长 3 结果的指标顺序不一致。');
    end
    metric = parameter.metric;
    historical = align_metrics(historical, metric);

    paperRSquared = [NaN; NaN; 0.87; 0.26; 0.78; 0.45; ...
        0.90; 0.49; 0.78; 0.50];
    paperRmse = [3.10; 1.41; nan(8, 1)];
    comparison = table(metric, paperRSquared, paperRmse, ...
        historical.n, historical.rSquared, historical.bias, ...
        historical.rmse, parameter.n, parameter.rSquared, ...
        parameter.bias, parameter.rmse, sample.n, sample.rSquared, ...
        sample.bias, sample.rmse, ...
        sample.rSquared - parameter.rSquared, ...
        sample.bias - parameter.bias, sample.rmse - parameter.rmse, ...
        'VariableNames', {'metric','paperRSquared','paperRmse', ...
        'historicalStride1N','historicalStride1RSquared', ...
        'historicalStride1Bias','historicalStride1Rmse', ...
        'parameterFirstN','parameterFirstRSquared', ...
        'parameterFirstBias','parameterFirstRmse', ...
        'sampleTbFirstN','sampleTbFirstRSquared', ...
        'sampleTbFirstBias','sampleTbFirstRmse', ...
        'deltaRSquared','deltaBias','deltaRmse'});
    writetable(comparison, fullfile(resultRoot, ...
        'three_way_metric_comparison.csv'));

    data = load(sampleMatFile, 'pairs');
    pairs = data.pairs;
    tbParameter = pairs.TBOIBMeanParameters;
    tbSample = pairs.TBOIBMeanSamples;
    tbObserved = pairs.TB;
    errorParameter = tbParameter - tbObserved;
    errorSample = tbSample - tbObserved;
    deltaTb = tbSample - tbParameter;
    diagnostics = [ ...
        summarize_group("all", true(height(pairs), 1), ...
        pairs, errorParameter, errorSample, deltaTb); ...
        summarize_group("2012", year(pairs.day) == 2012, ...
        pairs, errorParameter, errorSample, deltaTb); ...
        summarize_group("2015", year(pairs.day) == 2015, ...
        pairs, errorParameter, errorSample, deltaTb); ...
        summarize_group("FYI", ~pairs.isMYI, ...
        pairs, errorParameter, errorSample, deltaTb); ...
        summarize_group("MYI", pairs.isMYI, ...
        pairs, errorParameter, errorSample, deltaTb)];
    writetable(diagnostics, fullfile(resultRoot, ...
        'tb_operator_difference_diagnostics.csv'));

    plot_operator_comparison(pairs, tbObserved, tbParameter, ...
        tbSample, deltaTb, figureRoot);
    disp(comparison);
    disp(diagnostics);
end


function aligned = align_metrics(source, targetMetrics)
    aligned = table(targetMetrics, nan(numel(targetMetrics), 1), ...
        nan(numel(targetMetrics), 1), nan(numel(targetMetrics), 1), ...
        nan(numel(targetMetrics), 1), ...
        'VariableNames', {'metric','n','rSquared','bias','rmse'});
    for targetIndex = 1:numel(targetMetrics)
        sourceIndex = find(source.metric == targetMetrics(targetIndex), 1);
        if ~isempty(sourceIndex)
            aligned.n(targetIndex) = source.n(sourceIndex);
            aligned.rSquared(targetIndex) = source.rSquared(sourceIndex);
            aligned.bias(targetIndex) = source.bias(sourceIndex);
            aligned.rmse(targetIndex) = source.rmse(sourceIndex);
        end
    end
end


function row = summarize_group( ...
        group, mask, pairs, errorParameter, errorSample, deltaTb)
    currentDelta = deltaTb(mask);
    parameterError = errorParameter(mask);
    sampleError = errorSample(mask);
    row = table(group, nnz(mask), mean(currentDelta), ...
        median(currentDelta), std(currentDelta), ...
        prctile(currentDelta, 5), prctile(currentDelta, 95), ...
        sqrt(mean(parameterError .^ 2)), ...
        sqrt(mean(sampleError .^ 2)), ...
        sqrt(mean((parameterError - mean(parameterError)) .^ 2)), ...
        sqrt(mean((sampleError - mean(sampleError)) .^ 2)), ...
        100 * mean(abs(sampleError) < abs(parameterError)), ...
        nnz(abs(parameterError) <= 1.5), ...
        nnz(abs(sampleError) <= 1.5), mean(pairs.nOIB(mask)), ...
        'VariableNames', {'group','n','meanDeltaTbK','medianDeltaTbK', ...
        'stdDeltaTbK','p05DeltaTbK','p95DeltaTbK', ...
        'parameterFirstRmseK','sampleTbFirstRmseK', ...
        'parameterFirstCenteredRmseK','sampleTbFirstCenteredRmseK', ...
        'absoluteErrorImprovedPercent','parameterFirstNearTbN', ...
        'sampleTbFirstNearTbN','meanOibCount'});
end


function plot_operator_comparison( ...
        pairs, observed, parameterTb, sampleTb, deltaTb, figureRoot)
    blue = [0.00 0.45 0.70];
    orange = [0.90 0.62 0.00];
    red = [0.80 0.20 0.15];
    gray = [0.35 0.35 0.35];
    values = [observed; parameterTb; sampleTb];
    padding = 0.02 * (max(values) - min(values));
    limits = [min(values) - padding, max(values) + padding];

    figureHandle = figure('Visible', 'off', 'Color', 'w', ...
        'Position', [70 70 1500 560]);
    layout = tiledlayout(figureHandle, 1, 3, ...
        'TileSpacing', 'compact', 'Padding', 'compact');
    title(layout, '步长 3 下两种 TB 平均次序对比（同一 733 个配对）', ...
        'FontWeight', 'bold');
    draw_tb_panel(nexttile(layout), pairs, observed, parameterTb, ...
        limits, '先平均 hi/hs，再计算 TB', blue, orange, true);
    draw_tb_panel(nexttile(layout), pairs, observed, sampleTb, ...
        limits, '逐 OIB 点计算 TB，再平均', blue, orange, false);

    ax = nexttile(layout);
    histogram(ax, deltaTb, 32, 'FaceColor', blue, ...
        'FaceAlpha', 0.72, 'EdgeColor', 'w', ...
        'DisplayName', 'TB 差值分布');
    hold(ax, 'on');
    xline(ax, 0, 'k-', 'LineWidth', 1.1, 'DisplayName', '无差异');
    xline(ax, mean(deltaTb), '--', 'Color', red, 'LineWidth', 1.4, ...
        'DisplayName', sprintf('均值 %.2f K', mean(deltaTb)));
    xline(ax, median(deltaTb), ':', 'Color', gray, 'LineWidth', 1.4, ...
        'DisplayName', sprintf('中位数 %.2f K', median(deltaTb)));
    grid(ax, 'on'); box(ax, 'on');
    xlabel(ax, '逐样本平均 TB - 参数平均 TB (K)');
    ylabel(ax, '配对数');
    title(ax, '平均次序造成的 TB 差值');
    legend(ax, 'Location', 'northwest');
    text(ax, 0.04, 0.72, sprintf(['n=%d\n标准差=%.2f K\n' ...
        '绝对误差改善=%.1f%%'], numel(deltaTb), std(deltaTb), ...
        100 * mean(abs(sampleTb - observed) < ...
        abs(parameterTb - observed))), ...
        'Units', 'normalized', 'HorizontalAlignment', 'left', ...
        'VerticalAlignment', 'top', 'BackgroundColor', 'w', ...
        'Margin', 3);

    exportgraphics(figureHandle, fullfile(figureRoot, ...
        'stride3_tb_averaging_operator_comparison.png'), ...
        'Resolution', 300);
    close(figureHandle);
end


function draw_tb_panel( ...
        ax, pairs, observed, modeled, limits, panelTitle, blue, orange, showLegend)
    hold(ax, 'on');
    fyi = ~pairs.isMYI;
    myi = pairs.isMYI;
    scatter(ax, observed(fyi), modeled(fyi), 18, blue, '^', ...
        'filled', 'MarkerFaceAlpha', 0.48, 'MarkerEdgeAlpha', 0.35, ...
        'DisplayName', 'FYI');
    scatter(ax, observed(myi), modeled(myi), 18, orange, 's', ...
        'filled', 'MarkerFaceAlpha', 0.48, 'MarkerEdgeAlpha', 0.35, ...
        'DisplayName', 'MYI');
    plot(ax, limits, limits, 'k-', 'LineWidth', 1.1, ...
        'DisplayName', '1:1');
    fit = fit_retrieval(observed, modeled);
    plot(ax, limits, fit.slope .* limits + fit.intercept, '--', ...
        'Color', [0.35 0.35 0.35], 'LineWidth', 1.2, ...
        'DisplayName', 'OLS');
    xlim(ax, limits); ylim(ax, limits); axis(ax, 'square');
    grid(ax, 'on'); box(ax, 'on');
    xlabel(ax, 'SMOS 观测亮温 (K)');
    ylabel(ax, 'OIB 模拟亮温 (K)');
    title(ax, panelTitle);
    text(ax, 0.03, 0.97, sprintf(['R^2=%.2f\nbias=%.2f K\n' ...
        'RMSE=%.2f K'], fit.rSquared, fit.bias, fit.rmse), ...
        'Units', 'normalized', 'VerticalAlignment', 'top', ...
        'BackgroundColor', 'w', 'Margin', 3);
    if showLegend
        legend(ax, 'Location', 'southeast');
    end
end
