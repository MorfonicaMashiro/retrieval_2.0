function [pairs, metrics, summary] = ...
        run_stride3_kt19_surface_temperature_experiment(targetDays, outputStem)
%RUN_STRIDE3_KT19_SURFACE_TEMPERATURE_EXPERIMENT 逐点 KT19 表温敏感性。
%   保持步长 3、等权逐点 TB 平均、Burke、20 层冰、1 层雪，并按统一配置
%   对 Vb>70‰ 只标记、不截断。KT19_surf 用于真实温度廓线；仅把进入 Cox--Weeks 卤水经验式的
%   温度保护到 -30 degC。固定温度对照使用完全相同的 KT19 有效样本。

    if nargin < 1
        targetDays = datetime.empty(0,1);
    end
    if nargin < 2 || strlength(string(outputStem)) == 0
        outputStem = "kt19_surface_temperature_vb_uncapped_2012_2015";
    end
    targetDays = dateshift(datetime(targetDays(:)), 'start', 'day');
    outputStem = string(outputStem);

    branchRoot = fileparts(mfilename('fullpath'));
    matlabRoot = fileparts(fileparts(fileparts(branchRoot)));
    commonRoot = fullfile(fileparts(branchRoot), 'common');
    dataRoot = fullfile(fileparts(matlabRoot), 'data');
    resultRoot = fullfile(branchRoot, 'results');
    figureRoot = fullfile(branchRoot, 'figures');
    addpath(matlabRoot, fullfile(matlabRoot, 'readdata'), ...
        fullfile(matlabRoot, 'plot'), commonRoot, branchRoot);
    if ~isfolder(resultRoot), mkdir(resultRoot); end
    if ~isfolder(figureRoot), mkdir(figureRoot); end

    config = retrieval_config();
    fixedModel = config.model;
    fixedModel.surfaceTempC = config.temperature.fixedC;
    fixedModel.allowColdBrineExtrapolation = false;
    fixedModel.brineTemperatureFloorC = NaN;
    kt19Model = fixedModel;
    kt19Model.brineTemperatureFloorC = ...
        config.temperature.oibBrineFloorC;

    collocateOptions = struct('computeSampleMeanTB', true, ...
        'parameterWeighting', "none", 'centerStride', 3, ...
        'centerPhase', [2 2]);
    groupOptions = struct('centerStride', 3, 'centerPhase', [2 2], ...
        'weightingMode', "uniform", 'excludeNegativeSnowFreeboard', false, ...
        'includeSurfaceTemperature', true);

    flightFiles = find_flight_files(dataRoot, targetDays);
    if isempty(flightFiles)
        error('run_stride3_kt19_surface_temperature_experiment:NoFlights', ...
            '指定日期没有找到 2012/2015 OIB 飞行文件。');
    end

    pairs = table();
    summary = table();
    outputFile = fullfile(resultRoot, outputStem + ".mat");
    totalTimer = tic;
    for flightIndex = 1:height(flightFiles)
        day = flightFiles.day(flightIndex);
        token = char(string(day, 'yyyyMMdd'));
        oib = read_oib(char(flightFiles.path(flightIndex)));
        smosFile = fullfile(dataRoot, 'smos', char(string(year(day))), ...
            ['SMOS_TB_north_' token '.nc']);
        if ~isfile(smosFile)
            error('run_stride3_kt19_surface_temperature_experiment:MissingSMOS', ...
                '%s 缺少同日 SMOS 文件：%s', token, smosFile);
        end
        smosEase = grid_resampling.regrid_smos_to_ease( ...
            read_smos(smosFile), "EASE");
        [dailyPairs, collocateStats] = collocate_day( ...
            oib, smosEase, day, fixedModel, @tb_forward, collocateOptions);
        groups = build_stride3_point_groups( ...
            oib, dailyPairs, smosEase.grid, groupOptions);
        [dailyPairs, temperatureStats] = evaluate_temperature_inputs( ...
            dailyPairs, groups, fixedModel, kt19Model);
        pairs = [pairs; dailyPairs]; %#ok<AGROW>
        summary = [summary; table(day, collocateStats.rawPoints, ...
            collocateStats.qualityPoints, height(dailyPairs), ...
            temperatureStats.originalSamples, temperatureStats.kt19Samples, ...
            temperatureStats.missingSamples, ...
            temperatureStats.belowMinus30, ...
            temperatureStats.belowMinus35, ...
            temperatureStats.pairsWithKT19, ...
            temperatureStats.forwardSeconds, ...
            'VariableNames', {'day','rawPoints','qualityPoints', ...
            'matchedPairs','originalSamples','kt19Samples', ...
            'missingKT19Samples','belowMinus30Samples', ...
            'belowMinus35Samples','pairsWithKT19','forwardSeconds'})]; %#ok<AGROW>
        save(outputFile, 'pairs', 'summary', 'fixedModel', 'kt19Model', ...
            'collocateOptions', 'groupOptions', 'config', '-v7.3');
        elapsedMinutes = toc(totalTimer) / 60;
        etaMinutes = elapsedMinutes / flightIndex * ...
            (height(flightFiles) - flightIndex);
        fprintf(['[%d/%d] %s：步长3配对 %d，KT19有效点 %d/%d，' ...
            '<-30°C %d，前向 %.1f s；累计 %.1f min，预计剩余 %.1f min。\n'], ...
            flightIndex, height(flightFiles), token, height(dailyPairs), ...
            temperatureStats.kt19Samples, temperatureStats.originalSamples, ...
            temperatureStats.belowMinus30, temperatureStats.forwardSeconds, ...
            elapsedMinutes, etaMinutes);
    end

    pairs = sortrows(pairs, {'day','row','col'});
    summary = sortrows(summary, 'day');
    metrics = build_metrics(pairs);
    save(outputFile, 'pairs', 'summary', 'metrics', 'fixedModel', ...
        'kt19Model', 'collocateOptions', 'groupOptions', 'config', '-v7.3');
    writetable(pairs, fullfile(resultRoot, outputStem + "_pairs.csv"));
    writetable(summary, fullfile(resultRoot, outputStem + "_summary.csv"));
    writetable(metrics, fullfile(resultRoot, outputStem + "_metrics.csv"));
    plot_temperature_comparison(pairs, ...
        fullfile(figureRoot, outputStem + "_tb_comparison.png"));
    fprintf('KT19 表温试验完成：%d 条配对，总用时 %.1f min。\n%s\n', ...
        height(pairs), toc(totalTimer)/60, outputFile);
end

function [pairs, stats] = evaluate_temperature_inputs( ...
        pairs, groups, fixedModel, kt19Model)
    nPairs = height(pairs);
    originalCount = [groups.nSamples].';
    if any(originalCount ~= pairs.nOIB)
        error('run_stride3_kt19_surface_temperature_experiment:GroupMismatch', ...
            '逐点分组样本数与配对表 nOIB 不一致。');
    end
    total = sum(originalCount);
    pairIndex = zeros(total,1);
    hi = nan(total,1); hs = nan(total,1); ts = nan(total,1);
    weight = nan(total,1); isMYI = false(total,1);
    cursor = 0;
    for index = 1:nPairs
        count = groups(index).nSamples;
        selected = cursor + (1:count);
        pairIndex(selected) = index;
        hi(selected) = groups(index).hiTruth(:);
        hs(selected) = groups(index).hsTruth(:);
        ts(selected) = groups(index).surfaceTempC(:);
        weight(selected) = groups(index).weights(:);
        isMYI(selected) = groups(index).isMYI;
        cursor = cursor + count;
    end

    validKT19 = isfinite(ts) & ts < fixedModel.waterTempC;
    validIndex = find(validKT19);
    fixedPointTB = nan(nnz(validKT19),1);
    kt19PointTB = nan(nnz(validKT19),1);
    forwardTimer = tic;
    for iceType = [false true]
        selected = isMYI(validKT19) == iceType;
        if ~any(selected), continue; end
        fixedPointTB(selected) = tb_forward( ...
            hi(validIndex(selected)), hs(validIndex(selected)), ...
            iceType, fixedModel);
        pointModel = kt19Model;
        pointModel.surfaceTempC = ts(validIndex(selected));
        kt19PointTB(selected) = tb_forward( ...
            hi(validIndex(selected)), hs(validIndex(selected)), ...
            iceType, pointModel);
    end
    forwardSeconds = toc(forwardTimer);

    validPairIndex = pairIndex(validKT19);
    validWeights = weight(validKT19);
    denominator = accumarray(validPairIndex, validWeights, [nPairs 1], @sum, 0);
    fixedSame = accumarray(validPairIndex, ...
        validWeights .* fixedPointTB, [nPairs 1], @sum, 0) ./ denominator;
    kt19TB = accumarray(validPairIndex, ...
        validWeights .* kt19PointTB, [nPairs 1], @sum, 0) ./ denominator;
    fixedSame(denominator == 0) = NaN;
    kt19TB(denominator == 0) = NaN;

    nKT19 = accumarray(validPairIndex, 1, [nPairs 1], @sum, 0);
    meanKT19 = accumarray(validPairIndex, ts(validKT19), ...
        [nPairs 1], @mean, NaN);
    minKT19 = accumarray(validPairIndex, ts(validKT19), ...
        [nPairs 1], @min, NaN);
    maxKT19 = accumarray(validPairIndex, ts(validKT19), ...
        [nPairs 1], @max, NaN);
    nBelowMinus30 = accumarray(validPairIndex, ...
        double(ts(validKT19) < -30), [nPairs 1], @sum, 0);
    nBelowMinus35 = accumarray(validPairIndex, ...
        double(ts(validKT19) < -35), [nPairs 1], @sum, 0);
    retention = nKT19 ./ originalCount;
    retention(originalCount == 0) = NaN;
    kt19MinusFixed = kt19TB - fixedSame;
    fixedAll = pairs.TBOIBMeanSamples;
    pairs = addvars(pairs, fixedAll, fixedSame, kt19TB, ...
        kt19MinusFixed, nKT19, retention, meanKT19, minKT19, maxKT19, ...
        nBelowMinus30, nBelowMinus35, ...
        'NewVariableNames', {'TBOIBFixedMinus30All', ...
        'TBOIBFixedMinus30SameKT19','TBOIBKT19', ...
        'TBKT19MinusFixedSame','nKT19','kt19Retention', ...
        'meanKT19C','minKT19C','maxKT19C', ...
        'nKT19BelowMinus30','nKT19BelowMinus35'});

    stats = struct('originalSamples', total, ...
        'kt19Samples', nnz(validKT19), ...
        'missingSamples', total - nnz(validKT19), ...
        'belowMinus30', nnz(validKT19 & ts < -30), ...
        'belowMinus35', nnz(validKT19 & ts < -35), ...
        'pairsWithKT19', nnz(nKT19 > 0), ...
        'forwardSeconds', forwardSeconds);
end

function metrics = build_metrics(pairs)
    names = ["固定-30°C：全部OIB样本"; ...
        "固定-30°C：同一KT19有效样本"; ...
        "逐点KT19：卤水公式温度保护至-30°C"];
    modeled = {pairs.TBOIBFixedMinus30All; ...
        pairs.TBOIBFixedMinus30SameKT19; pairs.TBOIBKT19};
    metrics = table();
    for index = 1:numel(modeled)
        fit = fit_retrieval(pairs.TB, modeled{index});
        current = table(names(index), fit.n, fit.correlation, ...
            fit.rSquared, fit.bias, fit.rmse, fit.slope, fit.intercept, ...
            'VariableNames', {'metric','n','correlation','rSquared', ...
            'bias','rmse','slope','intercept'});
        metrics = [metrics; current]; %#ok<AGROW>
    end
end

function plot_temperature_comparison(pairs, pngPath)
    modeled = {pairs.TBOIBFixedMinus30All, ...
        pairs.TBOIBFixedMinus30SameKT19, pairs.TBOIBKT19};
    titles = {'固定 −30°C：全部样本', ...
        '固定 −30°C：KT19 有效样本', ...
        '逐点 KT19：卤水经验式低温保护'};
    figureHandle = figure('Visible','off','Color','w', ...
        'Position',[80 80 1500 470]);
    layout = tiledlayout(figureHandle,1,3, ...
        'TileSpacing','compact','Padding','compact');
    title(layout,'OIB 表面温度输入对前向亮温的影响', ...
        'FontName','Microsoft YaHei','FontWeight','bold');
    for panel = 1:3
        ax = nexttile(layout);
        valid = isfinite(pairs.TB) & isfinite(modeled{panel});
        fyi = valid & ~pairs.isMYI;
        myi = valid & pairs.isMYI;
        scatter(ax,pairs.TB(fyi),modeled{panel}(fyi),24, ...
            [0 114 189]/255,'o','filled','MarkerFaceAlpha',0.72); hold(ax,'on');
        scatter(ax,pairs.TB(myi),modeled{panel}(myi),30, ...
            [230 126 0]/255,'^','filled','MarkerFaceAlpha',0.72);
        bounds = [min([pairs.TB(valid); modeled{panel}(valid)]), ...
            max([pairs.TB(valid); modeled{panel}(valid)])];
        if all(isfinite(bounds))
            plot(ax,bounds,bounds,'k-','LineWidth',1.1);
            xlim(ax,bounds); ylim(ax,bounds);
        end
        fit = fit_retrieval(pairs.TB(valid),modeled{panel}(valid));
        text(ax,0.04,0.96,sprintf('n=%d  RMSE=%.2f K\nBias=%+.2f K  R^2=%.2f', ...
            fit.n,fit.rmse,fit.bias,fit.rSquared), ...
            'Units','normalized','VerticalAlignment','top', ...
            'FontName','Microsoft YaHei','FontSize',10, ...
            'BackgroundColor','w','Margin',4);
        title(ax,titles{panel},'FontName','Microsoft YaHei');
        xlabel(ax,'SMOS 观测亮温 (K)','FontName','Microsoft YaHei');
        ylabel(ax,'OIB 模拟亮温 (K)','FontName','Microsoft YaHei');
        grid(ax,'on'); ax.GridColor = [0.82 0.90 0.95];
        ax.FontName = 'Microsoft YaHei'; axis(ax,'square');
        if panel == 1
            legend(ax,{'FYI','MYI','1:1'},'Location','southeast', ...
                'FontName','Microsoft YaHei');
        end
    end
    exportgraphics(figureHandle,pngPath,'Resolution',300);
    close(figureHandle);
end

function flightFiles = find_flight_files(dataRoot, targetDays)
    specifications = { ...
        fullfile(dataRoot,'OIB','IDCSI4_L4','2012'),'IDCSI4_*.txt'; ...
        fullfile(dataRoot,'OIB','NSIDC-0708_QuickLook','2015_GR_NASA'), ...
        'OIB_*_IDCSI2*.txt'};
    days = datetime.empty(0,1);
    paths = strings(0,1);
    for specificationIndex = 1:size(specifications,1)
        files = dir(fullfile(specifications{specificationIndex,1}, ...
            specifications{specificationIndex,2}));
        for fileIndex = 1:numel(files)
            token = regexp(files(fileIndex).name,'(\d{8})','match','once');
            day = datetime(token,'InputFormat','yyyyMMdd');
            if isempty(targetDays) || ismember(day,targetDays)
                days(end+1,1) = day; %#ok<AGROW>
                paths(end+1,1) = string(fullfile( ...
                    files(fileIndex).folder,files(fileIndex).name)); %#ok<AGROW>
            end
        end
    end
    flightFiles = sortrows(table(days,paths, ...
        'VariableNames',{'day','path'}),'day');
end
