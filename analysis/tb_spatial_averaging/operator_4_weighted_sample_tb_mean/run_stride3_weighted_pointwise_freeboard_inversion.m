function [results, metricSummary, summary] = ...
        run_stride3_weighted_pointwise_freeboard_inversion( ...
        targetDays, outputStem, maxPairsPerDay)
%RUN_STRIDE3_WEIGHTED_POINTWISE_FREEBOARD_INVERSION 加权逐点联合反演。
%   权重按 2.5 km 等面积子网格去除航迹采样密度，不代表 SMOS 天线响应。

    if nargin < 1, targetDays = datetime.empty(0,1); end
    if nargin < 2
        outputStem = "stride3_pointwise_weighted_vb_uncapped_fixed_temp_2012_2015";
    end
    if nargin < 3, maxPairsPerDay = Inf; end
    routeRoot = fileparts(mfilename('fullpath'));
    commonRoot = fullfile(fileparts(routeRoot), 'common');
    addpath(commonRoot);
    route = struct('name', "pointwise_equal_area", ...
        'routeRoot', routeRoot, ...
        'weightingMode', "equal_area_subgrid", ...
        'subgridDivisions', 5, ...
        'maxPairsPerDay', maxPairsPerDay, ...
        'defaultOutputStem', ...
        "stride3_pointwise_weighted_vb_uncapped_fixed_temp_2012_2015", ...
        'contextLabel', ...
        "逐点干舷→逐点冰厚/雪深→逐点 TB→等面积子网格加权平均");
    [results, metricSummary, summary] = ...
        run_pointwise_freeboard_route(route, targetDays, outputStem);
end
