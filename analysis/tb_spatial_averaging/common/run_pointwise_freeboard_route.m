function [results, metricSummary, summary] = run_pointwise_freeboard_route( ...
        route, targetDays, outputStem)
%RUN_POINTWISE_FREEBOARD_ROUTE 运行逐点干舷—逐点 TB 的完整联合反演。

    if nargin < 2, targetDays = datetime.empty(0, 1); end
    if nargin < 3 || strlength(string(outputStem)) == 0
        outputStem = route.defaultOutputStem;
    end
    targetDays = dateshift(datetime(targetDays(:)), 'start', 'day');
    outputStem = string(outputStem);
    commonRoot = fileparts(mfilename('fullpath'));
    matlabRoot = fileparts(fileparts(fileparts(commonRoot)));
    dataRoot = fullfile(fileparts(matlabRoot), 'data');
    resultRoot = fullfile(route.routeRoot, 'results', 'pointwise_inversion');
    figureRoot = fullfile(route.routeRoot, 'figures', 'pointwise_inversion');
    addpath(matlabRoot, fullfile(matlabRoot, 'readdata'), ...
        fullfile(matlabRoot, 'plot'), commonRoot, route.routeRoot);
    if ~isfolder(resultRoot), mkdir(resultRoot); end
    if ~isfolder(figureRoot), mkdir(figureRoot); end

    retrievalConfig = retrieval_config();
    model = retrievalConfig.model;
    collocateOptions = retrievalConfig.collocation;
    collocateOptions.computeSampleMeanTB = false;
    collocateOptions.parameterWeighting = "none";
    groupOptions = struct('centerStride', 3, 'centerPhase', [2 2], ...
        'weightingMode', route.weightingMode, ...
        'subgridDivisions', route.subgridDivisions, ...
        'excludeNegativeSnowFreeboard', true, ...
        'includeSurfaceTemperature', ...
        retrievalConfig.temperature.source == "oib_kt19", ...
        'surfaceTemperatureField', retrievalConfig.temperature.oibField, ...
        'waterTempC', model.waterTempC);
    flightFiles = find_flight_files(dataRoot, targetDays);
    if isempty(flightFiles)
        error('run_pointwise_freeboard_route:NoFlights', ...
            '指定日期没有找到 2012/2015 OIB 飞行文件。');
    end

    results = table();
    summary = table();
    outputFile = fullfile(resultRoot, outputStem + ".mat");
    totalTimer = tic;
    for flightIndex = 1:height(flightFiles)
        day = flightFiles.day(flightIndex);
        token = char(string(day, 'yyyyMMdd'));
        oib = read_oib(char(flightFiles.path(flightIndex)));
        smosFile = fullfile(dataRoot, 'smos', char(string(year(day))), ...
            ['SMOS_TB_north_' token '.nc']);
        if ~isfile(smosFile)
            error('run_pointwise_freeboard_route:MissingSMOS', ...
                '%s 缺少同日 SMOS 文件：%s', token, smosFile);
        end
        smosEase = grid_resampling.regrid_smos_to_ease( ...
            read_smos(smosFile), retrievalConfig.data.gridVersion);
        [dailyPairs, collocateStats] = collocate_day( ...
            oib, smosEase, day, retrievalConfig);
        if isfield(route, 'maxPairsPerDay') && ...
                isfinite(route.maxPairsPerDay) && ...
                height(dailyPairs) > route.maxPairsPerDay
            dailyPairs = dailyPairs(1:route.maxPairsPerDay, :);
        end
        groups = build_stride3_point_groups( ...
            oib, dailyPairs, smosEase.grid, groupOptions);
        [dailyResults, solveStats] = solve_day( ...
            dailyPairs, groups, model, route, ...
            retrievalConfig.temperature.source);
        results = [results; dailyResults]; %#ok<AGROW>
        summary = [summary; table(day, height(dailyPairs), ...
            solveStats.validGroups, solveStats.forwardTruthPoints, ...
            solveStats.radarSolved, solveStats.laserSolved, ...
            solveStats.elapsedSeconds, collocateStats.rawPoints, ...
            collocateStats.qualityPoints, ...
            'VariableNames', {'day','matchedPairs','validGroups', ...
            'forwardTruthPoints','radarSolved','laserSolved', ...
            'solveSeconds','rawPoints','qualityPoints'})]; %#ok<AGROW>
        save(outputFile, 'results', 'summary', 'model', 'route', ...
            'collocateOptions', 'groupOptions', 'retrievalConfig', '-v7.3');
        fprintf(['[%d/%d] %s：%d 条；逐点 FBice 有解 %d，' ...
            '逐点 FBsnow 有解 %d；本日 %.1f min。\n'], ...
            flightIndex, height(flightFiles), token, height(dailyPairs), ...
            solveStats.radarSolved, solveStats.laserSolved, ...
            solveStats.elapsedSeconds / 60);
    end

    results = sortrows(results, {'day','row','col'});
    summary = sortrows(summary, 'day');
    nearTB = abs(results.tbFromOIB - results.TB) <= 1.5;
    metricSummary = summarize_retrieval_subset( ...
        results, true(height(results), 1), nearTB);
    metricByYear = summarize_retrieval_by_year(results, nearTB, ...
        fullfile(resultRoot, outputStem + "_metrics_by_year.csv"));
    save(outputFile, 'results', 'summary', 'metricSummary', ...
        'metricByYear', 'nearTB', 'model', 'route', ...
        'collocateOptions', 'groupOptions', 'retrievalConfig', '-v7.3');
    writetable(results, fullfile(resultRoot, outputStem + "_retrieval.csv"));
    writetable(summary, fullfile(resultRoot, outputStem + "_summary.csv"));
    writetable(metricSummary, ...
        fullfile(resultRoot, outputStem + "_metrics.csv"));
    plot_retrieval_validation(results, nearTB, false(height(results),1), ...
        figureRoot, char(route.contextLabel));
    fprintf('完成 %d 条真正逐点联合反演，总用时 %.1f min：%s\n', ...
        height(results), toc(totalTimer)/60, outputFile);
end

function [dailyResults, stats] = solve_day( ...
        pairs, groups, model, route, temperatureSource)
    n = height(pairs);
    originalFBsnow = pairs.FBsnow;
    originalFBice = pairs.FBice;
    originalHi = pairs.hi;
    originalHs = pairs.hs;
    originalNOIB = pairs.nOIB;
    fbSnow = nan(n,1); fbIce = nan(n,1);
    hiTruth = nan(n,1); hsTruth = nan(n,1);
    nRoute = zeros(n,1); tbFromOIB = nan(n,1);
    hiRadar = nan(n,1); hsRadar = nan(n,1);
    hiLaser = nan(n,1); hsLaser = nan(n,1);
    hiLaserAlt = nan(n,1); hsLaserAlt = nan(n,1);
    nRadarRoots = zeros(n,1); nLaserRoots = zeros(n,1);
    timer = tic;
    forwardTruthPoints = 0;
    for pairIndex = 1:n
        group = groups(pairIndex);
        if group.nSamples == 0, continue; end
        groupModel = model;
        if temperatureSource == "oib_kt19"
            groupModel.surfaceTempC = group.surfaceTempC(:);
        end
        weights = group.weights(:) / sum(group.weights);
        fbSnow(pairIndex) = sum(weights .* group.fbSnow(:));
        fbIce(pairIndex) = sum(weights .* group.fbIce(:));
        hiTruth(pairIndex) = sum(weights .* group.hiTruth(:));
        hsTruth(pairIndex) = sum(weights .* group.hsTruth(:));
        nRoute(pairIndex) = group.nSamples;
        truthTB = tb_forward(group.hiTruth(:), group.hsTruth(:), ...
            group.isMYI, groupModel);
        tbFromOIB(pairIndex) = sum(weights .* truthTB(:));
        forwardTruthPoints = forwardTruthPoints + group.nSamples;

        [radar, ~] = invert_pointwise_freeboard_pair( ...
            pairs.TB(pairIndex), group.fbIce, "ice", group.isMYI, ...
            groupModel, @tb_forward, group.weights);
        [laser, ~] = invert_pointwise_freeboard_pair( ...
            pairs.TB(pairIndex), group.fbSnow, "snow", group.isMYI, ...
            groupModel, @tb_forward, group.weights);
        nRadarRoots(pairIndex) = numel(radar);
        nLaserRoots(pairIndex) = numel(laser);
        if ~isempty(radar)
            hiRadar(pairIndex) = radar(1).hi;
            hsRadar(pairIndex) = radar(1).hs;
        end
        if ~isempty(laser)
            hiLaser(pairIndex) = laser(1).hi;
            hsLaser(pairIndex) = laser(1).hs;
        end
        if numel(laser) > 1
            hiLaserAlt(pairIndex) = laser(2).hi;
            hsLaserAlt(pairIndex) = laser(2).hs;
        end
    end
    dailyResults = pairs(:, {'day','flight','row','col','TB','isMYI'});
    dailyResults = addvars(dailyResults, fbIce, fbSnow, hiTruth, hsTruth, ...
        nRoute, originalFBice, originalFBsnow, originalHi, originalHs, ...
        originalNOIB, hiRadar, hsRadar, hiLaser, hsLaser, hiLaserAlt, ...
        hsLaserAlt, nRadarRoots, nLaserRoots, tbFromOIB, ...
        'NewVariableNames', {'FBice','FBsnow','hi','hs','nOIB', ...
        'FBiceOriginalMean','FBsnowOriginalMean','hiOriginalMean', ...
        'hsOriginalMean','nOIBOriginal','hiRadar','hsRadar','hiLaser', ...
        'hsLaser','hiLaserAlt','hsLaserAlt','nRadarRoots', ...
        'nLaserRoots','tbFromOIB'});
    stats = struct('validGroups', nnz(nRoute>0), ...
        'forwardTruthPoints', forwardTruthPoints, ...
        'radarSolved', nnz(nRadarRoots>0), ...
        'laserSolved', nnz(nLaserRoots>0), ...
        'elapsedSeconds', toc(timer), 'routeName', route.name);
end

function flightFiles = find_flight_files(dataRoot, targetDays)
    specifications = { ...
        fullfile(dataRoot,'OIB','IDCSI4_L4','2012'),'IDCSI4_*.txt'; ...
        fullfile(dataRoot,'OIB','NSIDC-0708_QuickLook','2015_GR_NASA'), ...
        'OIB_*_IDCSI2*.txt'};
    days = datetime.empty(0,1);
    paths = strings(0,1);
    for specificationIndex = 1:size(specifications,1)
        files = dir(fullfile(specifications{specificationIndex,1}, ...
            specifications{specificationIndex,2}));
        for fileIndex = 1:numel(files)
            token = regexp(files(fileIndex).name,'(\d{8})','match','once');
            day = datetime(token,'InputFormat','yyyyMMdd');
            if isempty(targetDays) || ismember(day,targetDays)
                days(end+1,1) = day; %#ok<AGROW>
                paths(end+1,1) = string(fullfile( ...
                    files(fileIndex).folder,files(fileIndex).name)); %#ok<AGROW>
            end
        end
    end
    flightFiles = sortrows(table(days,paths, ...
        'VariableNames',{'day','path'}),'day');
end
